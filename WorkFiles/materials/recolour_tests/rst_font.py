_CACHE = {}


def glyph(ch):
    ch = ch.upper()
    if ch not in _G:
        ch = "?"
    if ch not in _CACHE:
        _CACHE[ch] = np.array([[c == "1" for c in row] for row in _G[ch]], bool)
    return _CACHE[ch]


def draw_text(img, x, y, text, colour=(255, 255, 255), scale=2):
    """Draw text into an (H, W, 3) integer image at top-left (x, y). Returns the x after the text."""
    h, w = img.shape[:2]
    for ch in text:
        g = glyph(ch)
        g = np.kron(g, np.ones((scale, scale), bool))
        gh, gw = g.shape
        if y + gh <= h and x + gw <= w and x >= 0 and y >= 0:
            region = img[y:y + gh, x:x + gw]
            region[g] = colour
        x += gw + scale
    return x
