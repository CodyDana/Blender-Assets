"""One-off: copy WorkFiles/materials/material_spec.json to Scripts/unreal/materials/material_spec.json (the build's
source of truth) and apply what the map generators changed after the survey (recolour_maps.json):

  * T_PaperBomb_PaperDetail RGB is sRGB-ENCODED (import sRGB ON, TC_EditorIcon = uncompressed BGRA8); alpha linear
  * T_PaperBomb_InkWeights is linear, uncompressed (TC_VectorDisplacementmap)
  * the paper bomb's _M map is imported (unwired) with its own kind
  * GENERATOR values are resolved at build time from Exports/<Group>/Textures/Recolour/recolour_maps.json
"""
import json
from pathlib import Path

PROJ = Path(r"C:/Users/Cody/Desktop/Blender_Projects")
src = PROJ / "WorkFiles/materials/material_spec.json"
dst = PROJ / "Scripts/unreal/materials/material_spec.json"
s = json.loads(src.read_text(encoding="utf-8"))

s["schema"] = "ninjapack-material-spec/2"
s["status"] = ("BUILD SOURCE OF TRUTH. Copied from WorkFiles/materials/material_spec.json (survey design, 2026-09-26) by the "
               "material-author phase and updated with what the map generators changed (texture_import PaperDetail_sRGB / "
               "InkWeights_linear, the paper bomb's M map). Values written \"GENERATOR ...\" are resolved at build time from "
               "each item's recolour_maps.json (build.recolour_maps); a generator value always wins over a number typed here, "
               "and the build log lists every difference.")
s["build"] = {
    "entry": "Scripts/unreal/materials/build_pack_materials.py (one mode per Unreal process; run_build.sh runs them in order)",
    "texture_folder": "/Game/NinjaPack/Textures/<Exports group folder>  (Shuriken, SmokeBomb, BlackHat, PaperBomb)",
    "recolour_maps": {
        "Shuriken": "Exports/Shuriken/Textures/Recolour/recolour_maps.json",
        "SmokeBomb": "Exports/SmokeBomb/Textures/Recolour/recolour_maps.json",
        "BlackHat": "Exports/BlackHat/Textures/Recolour/recolour_maps.json",
        "PaperBomb": "Exports/PaperBomb/Textures/Recolour/recolour_maps.json"},
    "master_default_textures": {
        "M_Steel_Master": "Shuriken_FourPoint/0",
        "M_Fabric_Master": "SmokeBomb/0",
        "M_PaperInk_Master": "PaperBomb/0",
        "note": "a master's texture parameters default to one real slot's maps (a sampler type needs a texture of its kind); every instance overrides them"},
    "not_imported": {
        "Exports/SmokeBomb/Textures/T_SmokeBomb_Detail.png": "superseded by the lossless 16-bit linear Recolour/T_SmokeBomb_Detail16 (the sRGB G8 builds as BGRA8: ~85 MiB)",
        "Exports/BlackHat/Textures/T_BlackHat_Straw_Detail.png": "superseded by Recolour/T_BlackHat_Straw_Detail16",
        "Exports/BlackHat/Textures/T_BlackHat_Cloth_Detail.png": "superseded by Recolour/T_BlackHat_Cloth_Detail16"},
}
ti = s["texture_import"]
ti["PaperDetail_sRGB"] = {
    "srgb": True, "compression": "TC_EDITOR_ICON", "sampler": "SAMPLERTYPE_COLOR", "address": "Wrap",
    "mips": "TMGS_FROM_TEXTURE_GROUP", "pc_format": "B8G8R8A8 (uncompressed, sRGB)",
    "note": "T_PaperBomb_PaperDetail: RGB = paper weight / Paper Weight Scale, sRGB-ENCODED (the sampler decodes it); "
            "A = pooled red-ink weight, LINEAR (sRGB never touches alpha). Changed from the survey's linear BC7 by the "
            "generator: linear 8-bit RGB failed G-P1 by 4 levels under the black-ink cores; sRGB encoding holds 1 level."}
ti["InkWeights_linear"] = {
    "srgb": False, "compression": "TC_VECTOR_DISPLACEMENTMAP", "sampler": "SAMPLERTYPE_LINEAR_COLOR", "address": "Wrap",
    "mips": "TMGS_FROM_TEXTURE_GROUP", "pc_format": "B8G8R8A8 (uncompressed, linear)",
    "note": "T_PaperBomb_InkWeights: R black wet, G black dry, B red wet, A red dry. Uncompressed: G-P1 was measured "
            "on the uncompressed weights; BC7 was never measured"}
ti["PaperWeights"]["superseded_by"] = "PaperDetail_sRGB / InkWeights_linear (generator, 2026-09-26)"
ti["M_paperbomb"]["mips"] = "TMGS_FROM_TEXTURE_GROUP"
ti["M_paperbomb"]["sampler"] = "SAMPLERTYPE_MASKS"

for p in s["masters"]["M_PaperInk_Master"]["parameters"]:
    if p["name"] == "Paper Detail Map":
        p["sampler"] = "Color"
        p["desc"] = ("RGB = paper weight (stored sRGB-encoded, decoded by the sampler), A = pooled red-ink weight (linear). "
                     "Generated by make_paperbomb_recolour_maps.py")
    if p["name"] == "Ink Weights Map":
        p["desc"] = "R black ink wet, G black ink dry, B red ink wet, A red ink dry (linear weights)"

for item in s["items"]:
    if item["item"] != "PaperBomb":
        continue
    slot = item["slots"][0]
    slot["texture_kinds"]["Paper Detail Map"] = "PaperDetail_sRGB"
    slot["texture_kinds"]["Ink Weights Map"] = "InkWeights_linear"
    slot["unwired_texture_kinds"] = {"M": "M_paperbomb"}

dst.write_text(json.dumps(s, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print("wrote", dst)
