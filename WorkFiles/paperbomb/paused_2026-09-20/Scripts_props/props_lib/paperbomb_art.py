def palette_for(cfg: "ArtConfig | None") -> Palette:
    """The palette this config's ink-floor policy asks for."""
    mode = getattr(cfg, "ink_floor", DEFAULT_INK_FLOOR) if cfg is not None else DEFAULT_INK_FLOOR
    try:
        return PALETTES[mode]
    except KeyError:
        raise ValueError(f"unknown ink floor {mode!r}; expected one of {INK_FLOOR_MODES}")


def ink_floor(cfg: "ArtConfig | None") -> tuple[float, float]:
    """``(floor, ceiling)`` in LINEAR albedo for this config's policy."""
    pal = palette_for(cfg)
    return pal.floor_linear, pal.ceiling_linear


