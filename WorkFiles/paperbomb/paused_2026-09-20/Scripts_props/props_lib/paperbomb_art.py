CARD_W_MM = 70.0
CARD_H_MM = 156.0
#: REFERENCE_SPEC row 23 / worklist 21.  The first build read 7.6 mm off a
#: departure-threshold measurement that over-measures the bevel; fitting a line to the
#: bevel itself and intersecting it with the two straight edges gives 8.10 mm on V1 and
#: 7.97 on V2, and the ink pass got 8.09 / 7.96 independently.  8.05 is the adopted
#: figure.  ``props_lib.spec.CardSpec.corner_clip_mm`` carries the same number and
#: ``measure.corner_clip_agrees`` asserts the two have not drifted apart.
CORNER_CLIP_MM = 8.05          # 45 deg, four corners


def P(xf: float, yf: float) -> tuple[float, float]:
    """Card fraction -> card millimetres (x from the left, y from the top)."""
    return xf * CARD_W_MM, yf * CARD_H_MM


def to_px(path_mm, cfg) -> np.ndarray:
    """Card millimetres -> raster pixels.

    The island carries ``cfg.pad_mm`` of padding on every side so the bake has somewhere
    to bleed, and this is the ONE place that offset is applied.  Every element is drawn
    in plain card millimetres and never has to know the padding exists.
    """
    return (np.asarray(path_mm, np.float64) + cfg.pad_mm) * cfg.px


def mm_grid(cfg, H: int, W: int):
    """(y_mm, x_mm) broadcastable grids in card millimetres, padding removed."""
    yy = (np.arange(H, dtype=np.float32)[:, None] + 0.5) / cfg.px - cfg.pad_mm
    xx = (np.arange(W, dtype=np.float32)[None, :] + 0.5) / cfg.px - cfg.pad_mm
    return yy, xx


def raster_size(cfg) -> tuple[int, int]:
    W = int(round((CARD_W_MM + 2 * cfg.pad_mm) * cfg.px))
    H = int(round((CARD_H_MM + 2 * cfg.pad_mm) * cfg.px))
    return W, H


