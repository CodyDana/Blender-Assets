def _flame_strokes(rng, lay: Layout):
    """The emblem: FIVE separate brush strokes, thin - thick - thin - thick - thin.

    REFERENCE_SPEC row 11 / worklist 10, and correction 2 in section 5.  Our emblem's
    *box* was right to 0.45 mm and one pass concluded from that that the emblem matched.
    Its INK did not: one welded component of 268 mm2 where BOTH guides show five separate
    strokes totalling 167 mm2, and the two guides agree on that to 1.1 %, so it is not a
    pseudo-glyph artefact.  The reference's tongue widths alternate 1.79, 6.16, 1.46,
    6.50, 1.57 mm and its eye is 1.25 mm across against our 2.78.

    So the welded heart is gone.  What is here is five rising strokes that never touch -
    two loaded lobes carrying the body of the fire and three filaments between and
    outside them - with the spiral eye swept into the left lobe.  Section 7's test is the
    one that matters after the numbers: squint at the card and the eye should land on 爆
    first, the ring second, this third.

    Unit box, x in [-0.5, 0.5] and y in [0, 1] with y UP, the same convention the seal's
    device uses.  Returns ``[(path, width_fraction_of_h, load, profile), ...]``.
    """
    j = 0.014

    def jit(p, s=1.0):
        p = np.asarray(p, np.float64).copy()
        p[0] += s * rng.uniform(-j, j)
        p[1] += rng.uniform(-j, j) * 0.7
        return p

    def taper(n, peak, lo=0.30, tip=0.82):
        """One tongue's weight along its own length: pointed at BOTH ends.

        NORMALISED so its peak is exactly 1.0.  The measured tongue widths are the
        WIDEST point of each stroke, so a profile that peaks at 1.4 draws a mark 40 %
        heavier than the number it was given - which is most of the 268 mm2 the first
        version of this came out at against the reference's 167.

        Pointed at both ends is what makes the mark read as FIRE rather than as five
        leaves: the first arrangement was widest at the foot, which gave five blunt
        teardrops standing in a row, and it also forced the five bases apart because
        that is where they were fattest.  A tongue that starts at nothing can begin
        close to its neighbours and open out as it rises, which is the fan a flame is.
        """
        t = np.linspace(0.0, 1.0, n)
        body = np.sin(np.pi * np.clip(t, 0.0, 1.0) ** 0.86) ** 0.80
        bulge = 1.0 + 0.34 * np.exp(-((t - peak) / 0.24) ** 2)
        thin = 1.0 - 0.34 * tip * _smoothstep((t - 0.82) / 0.18)
        prof = body * bulge * thin
        return np.maximum(prof / max(float(prof.max()), 1e-6), lo * 0.05)

    # widths as fractions of the mark's HEIGHT, which is what flame_device multiplies
    # by.  The reference's box is 23.64 mm tall, so that is the divisor whatever
    # ``emblem_size_mm`` is set to - the mm figures in emblem_tongue_mm are absolute.
    # ``emblem_ink_scale`` is the last millimetre of the ink budget: the measured tongue
    # widths are the widest point of each stroke, and a brushed boundary plus the bleed
    # add a fraction of a millimetre all round, so drawing them at their nominal width
    # lands the mark a little over the reference's 167 mm2.
    wf = [w * lay.emblem_ink_scale / lay.emblem_size_mm[1] for w in lay.emblem_tongue_mm]

    # FIVE LANES THAT CANNOT TOUCH.  Each stroke keeps to its own column, and the
    # columns are spaced so that even the two widest neighbours clear each other by
    # about 0.9 mm - more than the ink bleed can wick across.  The first arrangement put
    # all five bases together at the foot of the mark and the measurement found three
    # welded components, which is the same failure the whole row is about.
    #
    #   centres  -0.420  -0.210   0.000  +0.212  +0.418     (fractions of the box width)
    #   widths     1.79    6.16    1.46    6.50    1.57  mm
    #
    # and the extremes land the ink box on the reference's 23.74 mm.
    strokes = []
    # 1 - outer left tongue: leaves the base, sweeps out over the shoulder, hooks back
    strokes.append((
        join(bezier(jit((-0.170, 0.020)), jit((-0.330, 0.080)),
                    (-0.412, 0.200), (-0.425, 0.340), 26),
             bezier((-0.425, 0.340), (-0.434, 0.460),
                    (-0.412, 0.530), (-0.368, 0.600), 18)),
        wf[0] * rng.uniform(0.94, 1.08), 0.86, taper(44, 0.30)))
    # 2 - left lobe: the loaded body of the fire, rising and curling in
    strokes.append((
        join(bezier(jit((-0.092, 0.000)), jit((-0.190, 0.130)),
                    (-0.222, 0.280), (-0.216, 0.420), 30),
             bezier((-0.216, 0.420), (-0.208, 0.590),
                    (-0.196, 0.720), (-0.156, 0.870), 22)),
        wf[1] * rng.uniform(0.96, 1.05), 1.00, taper(52, 0.38, tip=0.90)))
    # 3 - centre tongue: the tallest thing on the mark, an S that leans left
    strokes.append((
        join(bezier(jit((0.004, 0.010)), jit((-0.030, 0.230)),
                    (0.010, 0.420), (0.002, 0.600), 30),
             bezier((0.002, 0.600), (-0.008, 0.790),
                    (0.024, 0.900), (0.012, 1.000), 20)),
        wf[2] * rng.uniform(0.92, 1.10), 0.92, taper(50, 0.34)))
    # 4 - right lobe: the second loaded body, a shade fatter than the left
    strokes.append((
        join(bezier(jit((0.096, 0.000)), jit((0.194, 0.125)),
                    (0.224, 0.275), (0.218, 0.420), 30),
             bezier((0.218, 0.420), (0.212, 0.580),
                    (0.202, 0.700), (0.164, 0.850), 22)),
        wf[3] * rng.uniform(0.96, 1.05), 0.98, taper(52, 0.36, tip=0.90)))
    # 5 - outer right tongue
    strokes.append((
        join(bezier(jit((0.176, 0.020)), jit((0.332, 0.078)),
                    (0.414, 0.198), (0.427, 0.336), 26),
             bezier((0.427, 0.336), (0.436, 0.455),
                    (0.414, 0.525), (0.370, 0.595), 18)),
        wf[4] * rng.uniform(0.94, 1.08), 0.84, taper(44, 0.28)))

    # the eye: a small swept spiral cut into the LEFT lobe, 1.25 mm across on a 23.7 mm
    # mark.  Swept rather than constructed - a perfect Archimedean curve of constant
    # width is the most mechanical thing that can sit in the middle of a brushed mark.
    hc = (-0.219, 0.375)
    na = 150
    turns = 1.30
    a = np.linspace(rng.uniform(-0.4, 0.4), rng.uniform(-0.4, 0.4) + turns * 2.0 * math.pi, na)
    tt = np.linspace(0.0, 1.0, na)
    pitch = tt + 0.16 * np.sin(tt * math.pi * 1.7 + rng.uniform(0.0, 3.0)) * tt
    rmax = 0.5 * lay.emblem_eye_mm / 23.7
    r = 0.06 * rmax + (rmax - 0.06 * rmax) * np.clip(pitch, 0.0, 1.30)
    spiral = np.stack([hc[0] + r * np.cos(a), hc[1] + r * np.sin(a)], axis=1)
    spiral = wander(spiral, rng, 0.0016, 0.10)
    return strokes, spiral


def _flame_paths(rng, style: str = "emblem"):
    """Our flame: a bulbous heart with a spiral cut out of it and three rising tongues.

    Defined in a unit box, x in [-0.5, 0.5] and y in [0, 1] with y UP.  Symmetric about
    x = 0 by construction and then broken by a per-side jitter, because a hand cannot
    draw the same tongue twice.  Three tongues, two small outer flecks, one spiral heart
    - the brief's shape, drawn here from cubic segments this module defines.

    ``style`` = "emblem" is the tall mark at the top of the tag; "seal" is the stubbier,
    rounder cut in the big seal's panel, which has to read at 14 x 22 mm.
    """
    seal = style == "seal"
    # A hand cannot draw the same tongue twice, and the first pass's 0.026 was too
    # timid to break the mirror: the mark read as a logo because it WAS symmetric to
    # the eye.  0.068 is a visible difference between the two sides at 24 mm without
    # the mark losing its balance.
    j = 0.050 if not seal else 0.034

    def jit(p, side):
        p = np.asarray(p, np.float64).copy()
        p[0] += side * rng.uniform(-j, j)
        p[1] += rng.uniform(-j, j) * 0.7
        return p

    # ---- the heart: a flame bulb, broad across the shoulders, pointed at the foot.
    # The tongues start INSIDE it, at y ~ 0.34, so the mark reads as one body with fire
    # coming off it rather than as a blob with three hairs stuck on.
    # Wider across the shoulders than it is tall, with a flat-ish belly that comes to a
    # small point - a body of fire sitting down, not a ball.  A circle here is the thing
    # that makes a flame crest look like a logo.
    hw = 0.345 if not seal else 0.360
    top_y = 0.500 if not seal else 0.545
    heart = join(
        bezier((-hw, 0.225), (-hw * 1.04, 0.365), (-hw * 0.66, top_y),
               (-hw * 0.12, top_y * 0.98), 30),
        bezier((-hw * 0.12, top_y * 0.98), (hw * 0.34, top_y),
               (hw * 0.92, 0.390), (hw, 0.225), 30),
        bezier((hw, 0.225), (hw * 0.99, 0.105), (hw * 0.56, 0.032), (0.0, 0.012), 30),
        bezier((0.0, 0.012), (-hw * 0.56, 0.032), (-hw * 0.99, 0.105),
               (-hw, 0.225), 30),
    )
    heart = wander(heart, rng, 0.022, 0.30)

    tongues = []
    top = 1.00 if not seal else 0.97

    def swell(n: int, peak: float, lo: float = 0.34):
        """A 2:1-or-better weight profile down one tongue, with the bulge placed by hand.

        A tongue drawn at a constant taper is the other half of what made this mark read
        as vector art.  ``peak`` is where the brush was pressed hardest.
        """
        t = np.linspace(0.0, 1.0, n)
        body = (1.0 - t ** 1.45) ** 0.85
        bulge = 1.0 + 0.55 * np.exp(-((t - peak) / 0.24) ** 2)
        thin = 1.0 - 0.42 * np.exp(-((t - min(0.92, peak + 0.42)) / 0.13) ** 2)
        return np.maximum(body * bulge * thin, lo * 0.10)

    # centre tongue: an S that leans left, then straightens into a sharp tip
    tongues.append((
        join(bezier(jit((0.00, 0.34), 1), jit((-0.125, 0.52), 1),
                    jit((0.080, 0.66), 1), (0.040, 0.80), 40),
             bezier((0.040, 0.80), (0.018, 0.88), (0.050, 0.94), (0.022, top), 26)),
        (0.210 if not seal else 0.235) * rng.uniform(0.94, 1.10), 1.0,
        swell(40, rng.uniform(0.14, 0.26))))
    # side tongues: out over the shoulder, then up to a hooked tip.  Each side gets its
    # own width and its own bulge - they are two strokes, not one mirrored twice.
    for side in (1.0, -1.0):
        h = 0.80 if not seal else 0.74
        tongues.append((
            join(bezier(jit((side * 0.100, 0.30), side), jit((side * 0.290, 0.38), side),
                        jit((side * 0.390, 0.52), side), (side * 0.330, 0.66 + rng.uniform(-0.03, 0.03)), 34),
                 bezier((side * 0.330, 0.66), (side * 0.288, 0.73),
                        (side * 0.312, 0.77), (side * 0.250, h * rng.uniform(0.93, 1.06)), 22)),
            (0.170 if not seal else 0.195) * rng.uniform(0.88, 1.16), 0.96,
            swell(40, rng.uniform(0.12, 0.34))))
    # two small outer flares, clear of the body
    for side in (1.0, -1.0):
        tongues.append((
            bezier((side * 0.285, 0.165), (side * (0.405 + rng.uniform(-0.03, 0.03)), 0.215),
                   (side * 0.455, 0.320), (side * 0.400, 0.450 + rng.uniform(-0.04, 0.04)), 26),
            (0.082 if not seal else 0.098) * rng.uniform(0.85, 1.22), 0.85,
            swell(40, rng.uniform(0.10, 0.30))))

    # ---- the spiral eye, cut OUT of the heart.  Thin enough that the heart stays a
    # black mass with a spiral drawn through it, not a spiral with black round it.
    # It is SWEPT, not constructed: the pitch opens and closes and the line wanders,
    # because a perfect Archimedean curve of constant width is the single most
    # mechanical thing that can sit in the middle of a brushed mark.
    hc = (0.0, 0.272)
    turns = 1.45
    na = 240
    a = np.linspace(rng.uniform(-0.4, 0.4), rng.uniform(-0.4, 0.4) + turns * 2.0 * math.pi, na)
    tt = np.linspace(0.0, 1.0, na)
    pitch = tt + 0.16 * np.sin(tt * math.pi * 1.7 + rng.uniform(0.0, 3.0)) * tt
    r = 0.015 + (hw * 0.44 - 0.015) * np.clip(pitch, 0.0, 1.35)
    spiral = np.stack([hc[0] + r * np.cos(a), hc[1] - r * np.sin(a)], axis=1)
    spiral = wander(spiral, rng, 0.006, 0.22)
    spiral[:, 1] = hc[1] - (spiral[:, 1] - hc[1])        # y up in this box
    return tongues, heart, spiral, hc


def flame_device(cfg: ArtConfig, rng, W: int, H: int, cx: float, cy: float,
                 w_mm: float, h_mm: float, *, style: str = "emblem",
                 rotate_deg: float = 0.0, lay: Layout = None):
    """Rasterise the flame.  Returns (coverage, load, spiral_cut) at full raster size.

    ``cx, cy`` is the centre in card millimetres, y DOWN.  The unit box is mapped so
    the mark fills ``w_mm`` x ``h_mm``.

    ``style="emblem"`` is the five separate strokes REFERENCE_SPEC row 11 measures on
    the tag's own crest; ``style="seal"`` is the stubbier device knocked out of the big
    chop's panel, which section 6 confirms is already right (our inner 60 % of that box
    is 0.593 inked against the guide's 0.600) and which is therefore unchanged.
    """
    ppmm = cfg.px
    lay = LAYOUT if lay is None else lay

    def to_mm(p):
        p = np.asarray(p, np.float64)
        q = np.empty_like(p)
        q[:, 0] = cx + p[:, 0] * w_mm
        q[:, 1] = cy + (0.5 - p[:, 1]) * h_mm
        if rotate_deg:
            q = rotate_about(q, cx, cy, rotate_deg)
        return q

    cov = np.zeros((H, W), np.float32)
    load = np.zeros((H, W), np.float32)

    if style == "emblem":
        tongues, spiral = _flame_strokes(rng, lay)
        heart = None
    else:
        tongues, heart, spiral, _hc = _flame_paths(rng, style)

    if heart is not None:
        heart_cov = fill_path([to_px(to_mm(heart), cfg)], H, W)
        # The heart is a BRUSHED mass, not a filled bezier: it gets the same fibre-broken
        # boundary and the same starvation in its thin parts that every kanji on the card
        # gets.  Without this the emblem is the one mark on the tag drawn in a different
        # medium, and it reads as a sticker.
        heart_cov = _brush_up(heart_cov, rng, ppmm, ragged=0.40, dry=0.10)
        # A woodblock impression is solid but not flat: the paper's tooth keeps a little
        # of the block off the sheet.  That lives in the COVERAGE (paper showing
        # through), never in the load, or the mark goes grey-olive instead of textured.
        tooth = noise(rng, H, W, max(1.6, 0.62 * ppmm))
        cov = np.maximum(cov, heart_cov * (0.97 + 0.03 * tooth))
        hload = _ink_density(heart_cov, rng, ppmm, base=1.0, spread=0.16)
        load = np.where(heart_cov > load, hload, load)

    for path, wid, ld, prof_shape in tongues:
        p = to_mm(path)
        prof = wid * h_mm * np.asarray(prof_shape, np.float64)
        prof = np.maximum(prof, 0.02)
        # The emblem's dryness lives in the ink's DENSITY, not in lanes cut through it.
        # At dry 0.17 with dry_soft 0.70 the bristle field cut clean horizontal bands
        # across each lobe and the mark read as five striped feathers rather than as
        # fire; the marks are only 6 mm wide, so a lane is a third of a tongue.
        win = brush_stroke(p, prof, cfg=cfg, rng=rng, W=W, H=H, load=ld,
                           dry=0.07 if style == "emblem" else 0.17,
                           bristle_mm=0.30, streak_cell_mm=3.2,
                           edge_ragged=0.32, step_mm=0.22,
                           dry_soft=0.92 if style == "emblem" else 0.70, core=0.40)
        if win is not None:
            h_, w_ = win.shape
            sl = (slice(win.y0, win.y0 + h_), slice(win.x0, win.x0 + w_))
            m = win.cov > cov[sl]
            load[sl] = np.where(m, win.load, load[sl])
            cov[sl] = np.maximum(cov[sl], win.cov)

    # the spiral is CUT OUT of the mass - a carved line, so it is crisper than the
    # brushwork round it and barely breaks up at all
    sp = to_mm(spiral)
    t = np.linspace(0.0, 1.0, 40)
    # a swept cut, so its width swings better than 2:1 along the curl.  On the emblem it
    # has to fit inside a 1.25 mm eye (row 11), so it is a third of the seal's.
    k = 0.0085 if style == "emblem" else 0.024
    g = 0.0135 if style == "emblem" else 0.040
    sw = h_mm * (k + g * t) * (0.74 + 0.52 * noise(rng, 1, 40, 5.0)[0])
    sw *= 1.0 - 0.45 * _smoothstep((t - 0.86) / 0.14)
    cutw = brush_stroke(sp, sw, cfg=cfg, rng=rng, W=W, H=H, load=1.0, dry=0.0,
                        bristle_mm=0.20, streak_cell_mm=1.2, edge_ragged=0.26, step_mm=0.18,
                        aa=0.7)
    cut = np.zeros((H, W), np.float32)
    if cutw is not None:
        h_, w_ = cutw.shape
        sl = (slice(cutw.y0, cutw.y0 + h_), slice(cutw.x0, cutw.x0 + w_))
        cut[sl] = cutw.cov
        cov[sl] = np.clip(cov[sl] - cutw.cov * 0.98, 0.0, 1.0)
    return cov, np.clip(load, 0.0, 1.0), cut


def draw_emblem(black: Ink, cfg: ArtConfig, lay: Layout, W: int, H: int) -> None:
    rng = _rng(cfg.seed, "emblem")
    cx, cy = P(*lay.emblem_centre)
    w, h = lay.emblem_size_mm
    cov, load, cut = flame_device(cfg, rng, W, H, cx, cy, w, h, style="emblem",
                                  rotate_deg=rng.uniform(-1.4, 1.4), lay=lay)
    black.stamp_field(cov, np.clip(0.88 + 0.12 * load, 0.0, 1.0))
    black.protect(cut)


