def _radical_cluster(contours, gap_em: float = 0.028) -> list[int]:
    """Indices of the contours that form the character's LEFT-HAND radical, if any.

    Contours are grouped by their x spans: the radical is the leading group separated
    from everything else by a clear vertical corridor.  Returns ``[]`` when the glyph
    has no such separation, so a caller can only ever tighten a composition that
    genuinely has a detached element.
    """
    spans = sorted(((float(c[:, 0].min()), float(c[:, 0].max()), i)
                    for i, c in enumerate(contours)), key=lambda s: s[0])
    if len(spans) < 2:
        return []
    group = [spans[0]]
    reach = spans[0][1]
    for s in spans[1:]:
        if s[0] > reach + gap_em:
            break
        group.append(s)
        reach = max(reach, s[1])
    if len(group) == len(spans):
        return []
    return [s[2] for s in group]


def _glyph_cov(ch: str, cfg: ArtConfig, W: int, H: int, cx: float, cy: float,
               em_mm: float, rng, rot_deg: float = 0.0,
               transform=None, stretch_y: float = 1.0, stretch_x: float = 1.0,
               radical_tuck_mm: float = 0.0,
               fit_ink_mm: tuple[float, float] | None = None,
               fit_cell_mm: tuple[float, float] | None = None) -> tuple[np.ndarray, dict]:
    """One character, ink-bbox-centred on (cx, cy) in card millimetres.

    The glyph is scaled so its EM is ``em_mm`` - so 火 and 道 keep their true relative
    sizes inside a column - and then its INK box is centred on the cell, which is what
    gives a vertical column an even optical rhythm.  A tiny rotation per character keeps
    the column from looking set.

    ``radical_tuck_mm`` slides a detached left-hand radical toward the body before the
    ink box is measured.  REFERENCE_SPEC row 3: both guides set 爆 with the two parts'
    bounding boxes OVERLAPPING by 8.86 mm and only 0.75 mm of clear paper between the
    nearest ink, where MasaFont holds them 1.62 mm apart and the radical reads as a blot
    beside the character.  Tightening a composition is a calligrapher's decision applied
    to our own outlines; nothing is sampled from anything.
    """
    contours, meta = glyph_outline(ch, cfg.font)
    tucked: list[int] = []
    if radical_tuck_mm > 1e-6 and em_mm > 1e-6:
        tucked = _radical_cluster(contours)
        if tucked:
            shift = radical_tuck_mm / em_mm         # em units
            contours = [(c + np.array([shift, 0.0])) if i in tucked else c
                        for i, c in enumerate(contours)]
    if tucked:
        ix0 = float(min(c[:, 0].min() for c in contours))
        ix1 = float(max(c[:, 0].max() for c in contours))
        iy0 = float(min(c[:, 1].min() for c in contours))
        iy1 = float(max(c[:, 1].max() for c in contours))
    else:
        ix0, ix1 = meta["ink_x"]
        iy0, iy1 = meta["ink_y"]
    if fit_ink_mm is not None:
        # size to the INK BOX rather than to the em.  Tucking the radical in makes the
        # character narrower in em units, so an em that was chosen to draw a 59.30 mm
        # box stops doing so the moment the composition tightens.  REFERENCE_SPEC row 2
        # is a statement about the ink, not about the em, so the ink is what is fitted.
        want_w, want_h = fit_ink_mm
        em_mm = want_w / max(ix1 - ix0, 1e-9)
        stretch_y = want_h / max((iy1 - iy0) * em_mm, 1e-9)
    if fit_cell_mm is not None:
        # THE COLUMN CELL.  REFERENCE_SPEC row 5 measures the guide's three-glyph column
        # cells at 13.9 mm mean and 14.6 mm MAXIMUM - a spread of well under a
        # millimetre - because a brushed column is written into a ruled grid of cells and
        # every character is fitted to its own square.  MasaFont's outlines are not: at
        # one em its 爆 draws 16.54 mm of ink and its 炎 11.92, a 4.6 mm spread, which is
        # what pushed the upper-right block to within 0.50 mm of its own rule (row 12)
        # and put one cell 1.8 mm past the reference's stated maximum.
        #
        # So each character is scaled to the cell, and the distortion is SPLIT between
        # the two axes - the em is the geometric mean of the two fits - so no character
        # is squashed or stretched by more than about 12 % on either axis rather than one
        # of them taking 20 %.  Fitting a character to its cell is a decision a
        # calligrapher makes with a ruled sheet; it is applied to OUR outlines and
        # nothing is sampled from anything.
        cell_w, cell_h = fit_cell_mm
        sx = cell_w / max(ix1 - ix0, 1e-9)
        sy = cell_h / max(iy1 - iy0, 1e-9)
        em_mm = math.sqrt(max(sx * sy, 1e-12))
        stretch_x = sx / em_mm
        stretch_y = sy / em_mm
    gx = 0.5 * (ix0 + ix1)
    gy = 0.5 * (iy0 + iy1)
    polys = []
    for c in contours:
        p = np.empty_like(c)
        p[:, 0] = cx + (c[:, 0] - gx) * em_mm * stretch_x
        p[:, 1] = cy - (c[:, 1] - gy) * em_mm * stretch_y   # font y up, raster y down
        if rot_deg:
            p = rotate_about(p, cx, cy, rot_deg)
        if transform is not None:
            rot, dx, dy, tcx, tcy = transform
            p = rotate_about(p, tcx, tcy, rot, dx, dy)
        polys.append(to_px(p, cfg))
    cov = fill_path(polys, H, W)
    m = dict(meta)
    m["ink_w_mm"] = round((ix1 - ix0) * em_mm * stretch_x, 2)
    m["ink_h_mm"] = round((iy1 - iy0) * em_mm * stretch_y, 2)
    if abs(stretch_y - 1.0) > 1e-6:
        m["stretch_y"] = round(float(stretch_y), 4)
    if abs(stretch_x - 1.0) > 1e-6:
        m["stretch_x"] = round(float(stretch_x), 4)
    if tucked:
        m["radical_contours"] = len(tucked)
        m["radical_tuck_mm"] = round(float(radical_tuck_mm), 3)
    m["em_mm"] = round(em_mm, 2)
    m["centre_mm"] = (round(cx, 2), round(cy, 2))
    return cov, m


def _label_rows(mask: np.ndarray) -> tuple[np.ndarray, int]:
    """4-connected labelling by run-length union-find.  Rows only, so it is cheap."""
    m = np.asarray(mask, bool)
    H, W = m.shape
    lab = np.zeros((H, W), np.int32)
    parent = [0]

    def find(a):
        while parent[a] != a:
            parent[a] = parent[parent[a]]
            a = parent[a]
        return a

    nxt = 1
    for y in range(H):
        row = m[y]
        if not row.any():
            continue
        xs = np.flatnonzero(row)
        brk = np.flatnonzero(np.diff(xs) > 1)
        starts = np.concatenate(([0], brk + 1))
        ends = np.concatenate((brk, [len(xs) - 1]))
        prev = lab[y - 1] if y > 0 else None
        for s, e in zip(starts, ends):
            x0, x1 = int(xs[s]), int(xs[e]) + 1
            here = 0
            if prev is not None:
                above = prev[x0:x1]
                hit = above[above > 0]
                if hit.size:
                    here = int(hit.min())
                    for v in np.unique(hit):
                        ra, rb = find(here), find(int(v))
                        if ra != rb:
                            parent[max(ra, rb)] = min(ra, rb)
            if here == 0:
                here = nxt
                parent.append(nxt)
                nxt += 1
            lab[y, x0:x1] = here
    if nxt == 1:
        return lab, 0
    remap = np.zeros(nxt, np.int32)
    roots: dict[int, int] = {}
    for i in range(1, nxt):
        r = find(i)
        if r not in roots:
            roots[r] = len(roots) + 1
        remap[i] = roots[r]
    return remap[lab], len(roots)


def _join_broken_strokes(cov: np.ndarray, cfg: ArtConfig, rng, W: int, H: int, *,
                         max_gap_mm: float = 1.9, orphan_mm2: float = 150.0,
                         keep_mm: float = 0.0) -> tuple[np.ndarray, dict]:
    """Bridge strokes a loaded brush would not have lifted between.

    REFERENCE_SPEC row 3 and section 5's correction 7.  Both guides set 爆 as exactly
    TWO components; MasaFont's outline sets it as a body, a radical, an orphan flick and
    two strokes that do not quite reach the body, and at reading distance the loose ones
    read as smudges beside the character rather than as part of it.  A brush carrying
    enough ink to lay a 6 mm belly does not leave a 1 mm hole in the middle of a
    character, so every small piece within ``max_gap_mm`` of a bigger one gets the ink
    that joins it - drawn with this module's own brush, at the local stroke weight.

    ``keep_mm`` protects one deliberate separation: the left-hand radical is supposed to
    stay a separate component with about 0.75 mm of clear paper beside the body, so a
    piece whose nearest gap is at least this far is left alone.
    """
    ppmm = cfg.px
    m = cov > 0.5
    lab, n = _label_rows(m)
    if n < 2:
        return cov, {"bridges": 0, "components_before": n}
    areas = np.bincount(lab.ravel(), minlength=n + 1)
    order = np.argsort(-areas[1:]) + 1
    orphan_px = orphan_mm2 * ppmm * ppmm
    big = [int(k) for k in order if areas[k] > orphan_px]
    small = [int(k) for k in order if 4.0 * ppmm * ppmm < areas[k] <= orphan_px]
    if not big or not small:
        return cov, {"bridges": 0, "components_before": n}
    bridges = []
    out = cov
    for k in small:
        ys, xs = np.nonzero(lab == k)
        best = None
        for b in big:
            by, bx = np.nonzero(lab == b)
            # nearest pair, subsampled - these are hundreds of points, not millions
            sy, sx = ys[::3], xs[::3]
            ty, tx = by[::5], bx[::5]
            d2 = ((sy[:, None] - ty[None, :]) ** 2 + (sx[:, None] - tx[None, :]) ** 2)
            i, j = np.unravel_index(int(np.argmin(d2)), d2.shape)
            d = math.sqrt(float(d2[i, j])) / ppmm
            if best is None or d < best[0]:
                best = (d, (float(sx[i]), float(sy[i])), (float(tx[j]), float(ty[j])))
        if best is None:
            continue
        d, p0, p1 = best
        if d > max_gap_mm or d < 1e-6 or (keep_mm > 0.0 and d >= keep_mm):
            continue
        # A CONNECTING FLICK, not a stroke.  The bridge is the trail a brush leaves
        # when it does not quite lift, so it gets thinner relative to the gap as the
        # gap grows - a 6 mm reach is a hairline, a 1 mm one is nearly the stroke's own
        # weight.  Scaling the width WITH the gap draws a new stroke into the character,
        # which is not what row 3 is asking for.
        wid = float(np.clip(0.38 + 0.11 * d, 0.45, 1.25))
        path = np.stack([np.linspace(p0[0] / ppmm - cfg.pad_mm, p1[0] / ppmm - cfg.pad_mm, 12),
                         np.linspace(p0[1] / ppmm - cfg.pad_mm, p1[1] / ppmm - cfg.pad_mm, 12)],
                        axis=1)
        t = np.linspace(0.0, 1.0, 16)
        prof = wid * (0.72 + 0.46 * np.exp(-((t - 0.5) / 0.4) ** 2))
        win = brush_stroke(path, prof, cfg=cfg, rng=rng, W=W, H=H, load=1.0,
                           dry=0.0, bristle_mm=0.18, edge_ragged=0.30, step_mm=0.20,
                           core=0.3)
        if win is None:
            continue
        h_, w_ = win.shape
        sl = (slice(win.y0, win.y0 + h_), slice(win.x0, win.x0 + w_))
        out = out.copy()
        out[sl] = np.maximum(out[sl], win.cov)
        bridges.append({"gap_mm": round(d, 2), "width_mm": round(wid, 2)})
    lab2, n2 = _label_rows(out > 0.5)
    return out, {"bridges": len(bridges), "detail": bridges,
                 "components_before": n, "components_after": n2}


def _brush_up(cov: np.ndarray, rng, ppmm: float, *, ragged: float = 0.55,
              dry: float = 0.10, keep_joins: bool = False) -> np.ndarray:
    """Give a filled glyph a brush's edge: ragged where the edge is, nowhere else.

    MasaFont is already a brush face, so the stroke shapes and their weight variation
    come from the font and are not second-guessed here.  What a printed glyph needs on
    top is the paper: a fibre-broken boundary, and a little starvation in the thin fast
    parts where the tip was barely touching.

    ``keep_joins`` caps the starvation so that **no hole may cut a stroke**.  This is
    REFERENCE_SPEC row 3: the dry term targets exactly the THIN parts of a mark, which on
    a character is precisely where two strokes join, and at a mere dry=0.05 it severed
    three of them on the centre glyph - the reference has two components and we shipped
    five.  The medial core of every stroke is restored afterwards, so the edge can still
    starve and the skeleton cannot break.
    """
    H, W = cov.shape
    rag = noise(rng, H, W, max(1.6, 0.34 * ppmm))
    fine = noise(rng, H, W, max(1.2, 0.13 * ppmm))
    band = 4.0 * cov * (1.0 - cov)
    out = cov + band * ((rag - 0.5) * ragged + (fine - 0.5) * ragged * 0.55)
    if dry > 1e-4:
        thin = 1.0 - _smoothstep((blur(cov, 0.9 * ppmm) - 0.22) / 0.45)
        streak = fbm(rng, H, W, max(2.0, 0.9 * ppmm), octaves=3, aniso=3.0)
        out = out - thin * cov * dry * _smoothstep((streak - 0.56) / 0.22)
    out = np.clip(out, 0.0, 1.0)
    if keep_joins:
        core = _smoothstep((blur(cov, max(0.7, 0.30 * ppmm)) - 0.44) / 0.26)
        out = np.maximum(out, cov * core)
    return out


def _ink_density(cov: np.ndarray, rng, ppmm: float, base: float = 1.0,
                 spread: float = 0.30) -> np.ndarray:
    """A load field over one drawn mark: wet in the heavy strokes, thin in the fast ones.

    The first pass gave every glyph a load of ``base * (0.86 + 0.20 * noise)``, which
    clipped against 1.0 and left the whole black population inside 0.20 - 0.24 stored:
    dryness was expressed only as COVERAGE holes, so the study's "the first character is
    wettest, by the third the ink is 10 - 20 % lighter" was drawn but not visible.  Here
    the load also follows the local thickness of the mark - a blurred coverage is a good
    cheap proxy for how much ink the brush had to put down - so a fat stroke comes out
    near-black and a whipped-out tail comes out warm and grey.
    """
    H, W = cov.shape
    thick = _smoothstep((blur(cov, 0.62 * ppmm) - 0.34) / 0.46)
    n = noise(rng, H, W, max(2.0, 1.1 * ppmm))
    d = base * ((1.0 - spread * 1.55) + spread * (0.95 * thick + 0.60 * n))
    return np.clip(d, 0.0, 1.0).astype(np.float32)


def _dilate_px(mask: np.ndarray, r: int) -> np.ndarray:
    """Grow a boolean mask by ``r`` texels, separably."""
    m = np.asarray(mask, bool)
    if r <= 0:
        return m
    for axis in (0, 1):
        acc = m.copy()
        for k in range(1, r + 1):
            acc |= np.roll(m, k, axis=axis)
            acc |= np.roll(m, -k, axis=axis)
        m = acc
    return m


def _extend_radical_sweep(cov: np.ndarray, cfg: ArtConfig, lay: Layout,
                          W: int, H: int, rng) -> dict:
    """Carry the 火 radical's last right-falling stroke in under the body.

    REFERENCE_SPEC row 3, the clause a knob cannot reach.  Both guides set 爆 as two
    components whose BOUNDING BOXES overlap by 8.86 mm with only 0.75 mm of clear paper
    between the nearest ink - the radical's 捺 sweeps down and to the right and tucks in
    beside the body rather than stopping short of it.  MasaFont ends that stroke at the
    radical's own edge, so sliding the whole radical over (``centre_radical_tuck_mm``)
    buys overlap only by spending the gap: at 2.5 mm of tuck ours measured 0.54 mm of
    overlap with 0.85 mm of clear ink, and one more millimetre of tuck welds the two
    into one component.

    So the stroke is DRAWN, which is what the spec's own note says it will take.  It
    starts at the radical's existing rightmost ink, follows the body's left contour at a
    measured clearance, and stops where the corridor closes.  Nothing is sampled from
    anything: the path is generated from OUR raster's own geometry, the same way every
    other mark in this module is.  The clearance is enforced on the finished coverage -
    anything the sweep puts within ``gap`` of the body is erased - so the two components
    cannot weld however the brush lands, and the reach is backed off until the erasure
    costs less than a tenth of the stroke.
    """
    reach = float(getattr(lay, "centre_radical_sweep_mm", 0.0) or 0.0)
    if reach <= 0.0:
        return {"drawn": False, "reason": "disabled"}
    ppmm = cfg.px
    gap = float(lay.centre_radical_sweep_gap_mm)
    solid = cov > 0.5
    lab, n = _label_rows(solid)
    if n < 2:
        return {"drawn": False, "reason": "one component"}
    areas = np.bincount(lab.ravel())
    big = [i for i in range(1, n + 1)
           if areas[i] >= 15.0 * ppmm * ppmm]
    if len(big) < 2:
        return {"drawn": False, "reason": "fewer than two big components"}
    big.sort(key=lambda i: -areas[i])
    pair = big[:2]
    xs_of = {}
    for i in pair:
        ys, xs = np.nonzero(lab == i)
        xs_of[i] = (xs.min(), xs.max(), ys, xs)
    rad_i, bod_i = sorted(pair, key=lambda i: xs_of[i][0])
    rad = lab == rad_i
    bod = lab == bod_i

    # the body's left contour, per raster row, in pixels (W where the row is empty)
    body_left = np.full(H, W, np.int64)
    ys_b, xs_b = np.nonzero(bod)
    np.minimum.at(body_left, ys_b, xs_b)
    # the radical's rightmost ink, and where
    ys_r, xs_r = np.nonzero(rad)
    k = int(np.argmax(xs_r))
    tip_x, tip_y = int(xs_r[k]), int(ys_r[k])

    gap_px = gap * ppmm
    forbid = _dilate_px(bod, int(round(gap_px)))
    w_end = lay.centre_radical_sweep_end_w_mm
    # WHERE THE STROKE CAN GET TO.  The body's left contour is not a straight edge: it
    # steps out by three and a half millimetres below its own leftmost stroke, and that
    # step is the only corridor a 捺 can reach through.  So the far end is chosen first,
    # by scanning the contour for the row where a thin brush can sit furthest right and
    # still leave the clear paper the guides show, and the path is drawn TO it.
    # EVERY MARGIN HERE IS IN MILLIMETRES, not texels: a texel is 0.077 mm at the preview
    # resolution and 0.039 mm at the shipping supersample, and a margin that changes with
    # the raster makes the stroke a different length in the two.
    end_half = 0.5 * w_end * ppmm + 0.08 * ppmm
    rag_px = 0.05 * ppmm                     # what the ragged edge adds past the half
    marg_px = max(1, int(round(0.32 * ppmm)))
    best_y, best_x = -1, -1e9
    for y in range(tip_y + int(round(0.6 * ppmm)),
                   min(H, tip_y + int(round(reach * ppmm)))):
        # ...with two texels of margin on the window, because the corridor opens as a
        # STEP: a row chosen flush with the step is three millimetres of reach away from
        # a row one texel above it, and the path's own rounding then lands on the wrong
        # side of the cliff.
        lo = max(0, y - int(end_half) - marg_px); hi = min(H, y + int(end_half) + marg_px + 1)
        x = float(body_left[lo:hi].min()) - gap_px - end_half - rag_px
        if x > best_x:
            best_x, best_y = x, y
    if best_y < 0 or best_x - tip_x < 1.2 * ppmm:
        return {"drawn": False, "reason": "no corridor"}
    out: dict = {"drawn": False}
    tried: list = []
    for shrink in (1.0, 0.95, 0.90, 0.84, 0.76, 0.66, 0.54):
        ex = tip_x + (best_x - tip_x) * shrink
        ey = best_y
        m = 64
        t = np.linspace(0.0, 1.0, m)
        # descend clear of the body's leftmost stroke FIRST, then run flat underneath it
        # DOWN FIRST, THEN ACROSS.  The body's leftmost stroke sits at the same height as
        # the radical's terminal, and the corridor opens 0.9 mm below it, so a stroke
        # that runs right before it has dropped is simply inside the body.
        path0 = bezier((tip_x, tip_y),
                       (tip_x + 0.04 * (ex - tip_x), ey - 0.06 * (ey - tip_y)),
                       (tip_x + 0.38 * (ex - tip_x), ey),
                       (ex, ey), m)
        xs, ys = path0[:, 0].copy(), path0[:, 1].copy()
        # A STROKE, NOT A WHISKER.  A 捺 carries its weight most of the way and whips out
        # only at the very end; tapering it from the tip left a hairline poking out of
        # the radical, which is the failure mode section 7 warns about - a number in
        # tolerance and a mark that does not read as a brush.
        wid = (lay.centre_radical_sweep_w_mm
               + (w_end - lay.centre_radical_sweep_w_mm) * _smoothstep((t - 0.58) / 0.42))
        for j in range(m):
            half = int(round(0.5 * wid[j] * ppmm)) + max(1, int(round(0.155 * ppmm)))
            # the window spans the rows this SEGMENT covers, not just this sample's:
            # the descent moves several texels between samples and a per-sample window
            # leaves the ink between them unchecked
            ya = ys[max(0, j - 1)]; yb = ys[min(m - 1, j + 1)]
            lo = max(0, int(min(ya, ys[j], yb)) - half)
            hi = min(H, int(max(ya, ys[j], yb)) + half + 1)
            limit = (float(body_left[lo:hi].min()) - gap_px
                     - 0.5 * wid[j] * ppmm - rag_px)
            xs[j] = min(xs[j], limit)
        tried.append({"shrink": shrink, "x_gain_mm": round(float((xs.max() - tip_x) / ppmm), 2)})
        if xs.max() - tip_x < 1.2 * ppmm:
            tried[-1]["stop"] = "too short"
            continue
        path_mm = np.stack([xs / ppmm - cfg.pad_mm, ys / ppmm - cfg.pad_mm], axis=1)
        win = brush_stroke(path_mm, wid, cfg=cfg, rng=rng, W=W, H=H, load=1.0,
                           dry=0.05, bristle_mm=0.18, streak_cell_mm=3.0,
                           edge_ragged=0.30, step_mm=0.22, core=0.55)
        if win is None:
            tried[-1]["stop"] = "no window"
            continue
        add = np.zeros((H, W), np.float32)
        h_, w_ = win.shape
        add[win.y0:win.y0 + h_, win.x0:win.x0 + w_] = win.cov
        drawn = float(add.sum())
        # ENFORCE THE CLEARANCE ON THE FINISHED COVERAGE
        add = np.where(forbid, 0.0, add)
        kept = float(add.sum())
        tried[-1]["kept"] = round(kept / max(drawn, 1e-9), 3)
        if drawn <= 0.0 or kept / drawn < 0.88:
            tried[-1]["stop"] = "clearance erased too much"
            continue
        new = np.maximum(cov, add)
        lab2, n2 = _label_rows(new > 0.5)
        a2 = np.bincount(lab2.ravel())
        nbig = sum(1 for i in range(1, n2 + 1) if a2[i] >= 15.0 * ppmm * ppmm)
        tried[-1]["components"] = nbig
        if nbig != 2:
            tried[-1]["stop"] = "welded" if nbig < 2 else "split"
            continue
        cov[...] = new
        rx1 = float(np.nonzero(add.any(axis=0))[0].max())
        out = {"drawn": True,
               "reach_mm": round(float((ex - tip_x) / ppmm), 2),
               "erased_fraction": round(1.0 - kept / drawn, 3),
               "tip_mm": [round(tip_x / ppmm - cfg.pad_mm, 2),
                          round(tip_y / ppmm - cfg.pad_mm, 2)],
               "new_radical_x1_mm": round(rx1 / ppmm - cfg.pad_mm, 2)}
        break
    out["tried"] = tried
    return out


def typeset(black: Ink, red: Ink, cfg: ArtConfig, lay: Layout, W: int, H: int,
            seal_info: dict, centre_cov: np.ndarray | None = None) -> dict:
    """Every character on the tag, cell by cell, top to bottom.

    Load falls off down a column: the first character is the wettest and darkest and by
    the third the brush is 10 - 20 % lighter (study 5.5).

    ``centre_cov`` is the hero glyph's finished coverage, built BEFORE the columns so
    the columns can leave it ``lay.column_centre_clear_mm`` of paper.  Both guides run
    the lower-right column through 爆's bounding box without touching its ink; the
    second build ran it through the ink and welded the two into one mark.
    """
    strings = dict(TEXT)
    report: dict[str, list] = {}
    ppmm = cfg.px

    clear = None
    if centre_cov is not None and float(lay.column_centre_clear_mm) > 0.0:
        px = max(1, int(round(float(lay.column_centre_clear_mm) * ppmm)))
        clear = (~_dilate_px(centre_cov > 0.45, px)).astype(np.float32)

    def column(slot, s, xf, ys, em_mm, layer, load0=1.0, colour="black",
               transform=None, cell_mm=None, keep_clear=False):
        rng = _rng(cfg.seed, "text_" + slot)
        rows = []
        cx = xf * CARD_W_MM
        for i, ch in enumerate(s):
            cy = ys[i] * CARD_H_MM
            rot = rng.uniform(-2.2, 2.2)
            jx = rng.uniform(-0.22, 0.22)
            jy = rng.uniform(-0.22, 0.22)
            cov, meta = _glyph_cov(ch, cfg, W, H, cx + jx, cy + jy, em_mm, rng,
                                   rot_deg=rot, transform=transform,
                                   fit_cell_mm=cell_mm)
            k = len(s)
            # study 5.5: the first character is wettest, by the last the brush is
            # 10 - 20 % lighter.  0.22 rather than 0.16 because the load now has to
            # carry a visible value change, not just a number in the report.
            load = load0 * (1.0 - 0.22 * (i / max(k - 1, 1)))
            load *= rng.uniform(0.96, 1.04)
            dry = 0.06 + 0.16 * (i / max(k - 1, 1))
            cov = _brush_up(cov, rng, ppmm, ragged=0.52, dry=dry)
            if keep_clear and clear is not None:
                before = float(cov.sum())
                cov = cov * clear
                after = float(cov.sum())
                meta["centre_clearance_erased"] = round(
                    1.0 - after / max(before, 1e-9), 4)
            layer.stamp_field(cov, _ink_density(cov, rng, ppmm, base=load, spread=0.30))
            meta["slot"] = slot
            meta["cell"] = i
            meta["colour"] = colour
            meta["load"] = round(float(load), 3)
            rows.append(meta)
        report[slot] = rows

    column("upper_left", strings["upper_left"], lay.col_upper_left_x,
           lay.col_upper_y, 0.0, black, 1.0, cell_mm=lay.col_upper_cell_mm,
           keep_clear=True)
    column("upper_right", strings["upper_right"], lay.col_upper_right_x,
           lay.col_upper_y, 0.0, black, 0.97, cell_mm=lay.col_upper_cell_mm,
           keep_clear=True)
    column("lower_right", strings["lower_right"], lay.col_lower_right_x,
           lay.col_lower_right_y, 0.0, black, 0.94,
           cell_mm=lay.col_lower_right_cell_mm, keep_clear=True)
    column("lower_centre", strings["lower_centre"], lay.col_lower_centre_x,
           lay.col_lower_centre_y, 0.0, black, 0.98,
           cell_mm=lay.col_lower_centre_cell_mm, keep_clear=True)
    # the small seal's characters ride WITH the stamp, so they take the box's own
    # rotation and offset: a chop prints its frame and its mark in one press
    column("small_seal", strings["small_seal"], lay.small_seal_x, lay.small_seal_y,
           lay.small_seal_em_mm, red, 0.92, colour="red",
           transform=seal_info.get("small_seal_transform"))
    return report


def typeset_centre(black: Ink, cfg: ArtConfig, lay: Layout, W: int, H: int) -> dict:
    """The centre character - a fully loaded brush, the darkest, wettest mark on the tag.

    REFERENCE_SPEC rows 2 and 3 / worklist 2 and 3.  59.30 x 52.38 mm of ink, WIDER than
    it is tall (w/h 1.132), spanning 84.7 % of the card's width, in exactly TWO
    components.  Ours was 47.82 x 44.18 in five pieces - a body, the radical, an orphan
    flick and two strokes broken out of the body - which at reading distance is a blot
    beside a character and a smudge below it.  The erosion is capped (``keep_joins``) so
    no hole may cut a stroke, the radical is tucked in, and the component count is a
    BUILD GATE so this cannot drift back.
    """
    cov, meta, rng = build_centre(cfg, lay, W, H)
    stamp_centre(black, cov, meta, rng, cfg)
    return meta


def build_centre(cfg: ArtConfig, lay: Layout, W: int, H: int):
    """The hero glyph's finished coverage, WITHOUT stamping it.

    Split out in the third build so the columns can be clipped clear of it - see
    ``typeset`` and ``Layout.column_centre_clear_mm``.  The stream is the same
    ``_rng(seed, "text_centre")`` it always was and it is consumed in the same order,
    so building it earlier changes no pixel of the glyph itself.
    """
    rng = _rng(cfg.seed, "text_centre")
    ch = dict(TEXT)["centre"]
    cx, cy = P(*lay.centre_char)
    cov, meta = _glyph_cov(ch, cfg, W, H, cx, cy, lay.centre_em_mm, rng,
                           rot_deg=rng.uniform(-1.2, 1.2),
                           stretch_y=lay.centre_stretch_y,
                           radical_tuck_mm=lay.centre_radical_tuck_mm,
                           fit_ink_mm=lay.centre_ink_mm)
    cov, join_info = _join_broken_strokes(cov, cfg, rng, W, H,
                                          max_gap_mm=lay.centre_join_gap_mm,
                                          orphan_mm2=lay.centre_join_orphan_mm2)
    sweep = _extend_radical_sweep(cov, cfg, lay, W, H, rng)
    cov = _brush_up(cov, rng, cfg.px, ragged=0.46, dry=0.05, keep_joins=True)
    meta["slot"] = "centre"
    meta["colour"] = "black"
    meta["joins"] = join_info
    meta["radical_sweep"] = sweep
    return cov, meta, rng


def stamp_centre(black: Ink, cov: np.ndarray, meta: dict, rng, cfg: ArtConfig) -> dict:
    black.stamp_field(cov, _ink_density(cov, rng, cfg.px, base=1.0, spread=0.15))
    return meta


