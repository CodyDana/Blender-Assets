def linear_to_srgb(x: np.ndarray) -> np.ndarray:
    x = np.clip(x, 0.0, 1.0)
    return np.where(x <= 0.0031308, x * 12.92, 1.055 * np.power(x, 1.0 / 2.4) - 0.055)


def _png_chunk(tag: bytes, payload: bytes) -> bytes:
    return (struct.pack(">I", len(payload)) + tag + payload
            + struct.pack(">I", zlib.crc32(tag + payload) & 0xFFFFFFFF))


def write_png(path: str, arr: np.ndarray, bits: int = 8) -> str:
    """Write a PNG with no dependency on PIL or on Blender's image system."""
    a = np.asarray(arr)
    if a.ndim == 2:
        a = a[:, :, None]
    H, W, C = a.shape
    ctype = {1: 0, 2: 4, 3: 2, 4: 6}[C]
    if bits == 16:
        data = np.clip(a, 0.0, 1.0) * 65535.0
        px = data.astype(">u2").reshape(H, W * C).view(np.uint8)
    else:
        data = np.clip(a, 0.0, 1.0) * 255.0
        px = (data + 0.5).astype(np.uint8).reshape(H, W * C)
    raw = np.zeros((H, px.shape[1] + 1), np.uint8)
    raw[:, 1:] = px
    os.makedirs(os.path.dirname(os.path.abspath(path)) or ".", exist_ok=True)
    with open(path, "wb") as f:
        f.write(b"\x89PNG\r\n\x1a\n")
        f.write(_png_chunk(b"IHDR", struct.pack(">IIBBBBB", W, H, bits, ctype, 0, 0, 0)))
        f.write(_png_chunk(b"IDAT", zlib.compress(raw.tobytes(), 6)))
        f.write(_png_chunk(b"IEND", b""))
    return path


def save_art(art: TagArt, out_dir: str, prefix: str) -> dict:
    """Write the layers as PNGs.  Base colour is sRGB-encoded; every mask is linear."""
    os.makedirs(out_dir, exist_ok=True)
    p = {}
    p["bc"] = write_png(os.path.join(out_dir, prefix + "_bc.png"),
                        linear_to_srgb(art.base_colour))
    p["paper"] = write_png(os.path.join(out_dir, prefix + "_paper.png"),
                           linear_to_srgb(art.paper_rgb))
    p["rough"] = write_png(os.path.join(out_dir, prefix + "_rough.png"), art.roughness)
    p["relief"] = write_png(os.path.join(out_dir, prefix + "_relief.png"),
                            np.clip(art.relief / 0.12 * 0.5 + 0.5, 0, 1), bits=16)
    p["card"] = write_png(os.path.join(out_dir, prefix + "_card.png"), art.card_mask)
    p["fringe"] = write_png(os.path.join(out_dir, prefix + "_fringe.png"), art.fringe)
    p["scorch"] = write_png(os.path.join(out_dir, prefix + "_scorch.png"), art.scorch)
    p["inkmask"] = write_png(os.path.join(out_dir, prefix + "_inkmask.png"), art.ink_mask)
    if art.ink_black is not None:
        p["black"] = write_png(os.path.join(out_dir, prefix + "_ink_black.png"),
                               art.ink_black.a)
        p["red"] = write_png(os.path.join(out_dir, prefix + "_ink_red.png"), art.ink_red.a)
        p["load"] = write_png(
            os.path.join(out_dir, prefix + "_ink_load.png"),
            np.stack([art.ink_red.d * art.ink_red.a, art.ink_black.d * art.ink_black.a,
                      np.zeros_like(art.ink_red.d)], axis=2))
    return p


def contact_sheet(path: str, panels: Sequence[tuple[str, np.ndarray]],
                  height: int = 1100, gap: int = 12) -> str:
    """One image with every panel side by side, so the art can be judged by LOOKING."""
    imgs = []
    for _name, a in panels:
        a = np.asarray(a, np.float32)
        if a.ndim == 2:
            a = np.repeat(a[:, :, None], 3, axis=2)
        h, w = a.shape[:2]
        nw = max(1, int(round(w * height / h)))
        out = np.empty((height, nw, 3), np.float32)
        for c in range(3):
            out[:, :, c] = _resize_bilinear(a[:, :, c], height, nw)
        imgs.append(np.clip(out, 0, 1))
    total = sum(i.shape[1] for i in imgs) + gap * (len(imgs) + 1)
    sheet = np.full((height + 2 * gap, total, 3), 0.16, np.float32)
    x = gap
    for i in imgs:
        sheet[gap:gap + height, x:x + i.shape[1]] = i
        x += i.shape[1] + gap
    return write_png(path, sheet)


