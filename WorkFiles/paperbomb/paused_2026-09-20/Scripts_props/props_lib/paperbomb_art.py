@dataclass
class TagArt:
    """Everything the material and the bake need, at one resolution.  See the docstring."""

    side: str
    ppmm: float
    width: int
    height: int
    base_colour: np.ndarray
    paper_rgb: np.ndarray
    roughness: np.ndarray
    relief: np.ndarray
    card_mask: np.ndarray
    fringe: np.ndarray
    scorch: np.ndarray
    ink_mask: np.ndarray
    ink_black: Ink | None = None
    ink_red: Ink | None = None
    outline_mm: np.ndarray | None = None
    report: dict = field(default_factory=dict)


def _card_mask(cfg: ArtConfig, lay: Layout, W: int, H: int):
    outline = card_outline_mm(cfg, lay)
    card = fill_path([to_px(outline, cfg)], H, W, ss=4)
    return card, outline


def _fringe_field(cfg: ArtConfig, lay: Layout, card: np.ndarray,
                  W: int, H: int) -> np.ndarray:
    """The torn edge's fibre fringe, 0.4 - 0.8 mm of loose kozo, only where it tore."""
    rng = _rng(cfg.seed, "fringe")
    ppmm = cfg.px
    lo, hi = lay.fringe_mm
    grown = blur(card, hi * ppmm * 0.9)
    halo = np.clip(_smoothstep((grown - 0.06) / 0.32) - card, 0.0, 1.0)
    # only the bottom torn stretch and the right-edge nick carry a fringe
    gate = _tear_gate(cfg, lay, W, H)
    hair = fbm(rng, H, W, max(1.6, 0.30 * ppmm), octaves=3, aniso=2.6)
    fringe = halo * gate * _smoothstep((hair - 0.42) / 0.30)
    frac = lo / hi
    return np.clip(fringe * (frac + (1.0 - frac) * hair), 0.0, 1.0).astype(np.float32)


def _tear_gate(cfg: ArtConfig, lay: Layout, W: int, H: int) -> np.ndarray:
    """1 along the torn bottom stretch and the right-edge nick, 0 on the cut edges."""
    yy, xx = mm_grid(cfg, H, W)
    gate = _smoothstep((yy - (CARD_H_MM - 3.0)) / 2.0)
    nick = (np.exp(-((yy - CARD_H_MM * lay.nick_y) / 4.0) ** 2)
            * _smoothstep((xx - (CARD_W_MM - 4.0)) / 2.5))
    return np.clip(gate + nick, 0.0, 1.0).astype(np.float32)


def _torn_feather(cfg: ArtConfig, lay: Layout, card: np.ndarray,
                  W: int, H: int) -> np.ndarray:
    """The loose fibre just INSIDE a torn edge, for the BASE COLOUR.

    Study open question 3, answered honestly.  The torn OUTLINE is geometry and the
    master material is opaque, so the 0.4 - 0.8 mm fringe cannot live in an alpha that
    nothing samples: the first build shipped it in ``_M`` red, left the channel unwired,
    and the tear read as a die-cut wavy line with a hard silhouette.  Washi tears with a
    soft feathered edge because the long kozo fibres pull apart rather than cut, and the
    loose fibre at the break sits proud, catches light and reads LIGHTER than the sheet.
    That is paint, and it works on an opaque material at every LOD and in every mip.
    """
    rng = _rng(cfg.seed, "feather")
    ppmm = cfg.px
    lo, hi = lay.fringe_mm
    inward = np.clip((blur(card, hi * ppmm * 1.2) - 0.5) * 2.0, 0.0, 1.0)
    band = card * (1.0 - _smoothstep(inward / 0.62))
    hair = fbm(rng, H, W, max(1.6, 0.26 * ppmm), octaves=3, aniso=0.30)
    frac = lo / hi
    out = band * _tear_gate(cfg, lay, W, H) * _smoothstep((hair - 0.36) / 0.34)
    return np.clip(out * (frac + (1.0 - frac) * hair), 0.0, 1.0).astype(np.float32)


def _scorch_field(cfg: ArtConfig, lay: Layout, W: int, H: int) -> np.ndarray:
    """0 at the Fuse socket, 1 at the far end, with a ragged front.  -> T_PaperBomb_M.G"""
    rng = _rng(cfg.seed, "scorch")
    ppmm = cfg.px
    fx, fy = P(*lay.fuse_point)
    yy, xx = mm_grid(cfg, H, W)
    d = np.hypot(xx - fx, (yy - fy) * 0.86)
    dmax = float(np.hypot(max(fx, CARD_W_MM - fx), max(fy, CARD_H_MM - fy)))
    g = d / max(dmax, 1e-6)
    g = g + (fbm(rng, H, W, 7.0 * ppmm, octaves=4) - 0.5) * 0.13
    return np.clip(g, 0.0, 1.0).astype(np.float32)


#: how much LIGHTER than the sheet the loose fibre at a tear sits, as a fraction of the
#: way from the paper colour to white.  Held as a ratio rather than as an absolute so it
#: follows the ink-floor policy's paper instead of contradicting it.
TORN_FIBRE_LIFT = 0.17


def torn_fibre_linear(cfg: "ArtConfig | None" = None) -> tuple[float, float, float]:
    """Linear albedo of the fibre standing proud at a tear, for this policy's paper."""
    pal = palette_for(cfg)
    _floor, ceil_lin = ink_floor(cfg)
    return tuple(float(min(ceil_lin, c + (1.0 - c) * TORN_FIBRE_LIFT)) for c in pal.paper)


#: kept as a name for the report; it is the reference policy's value
TORN_FIBRE_LINEAR = torn_fibre_linear(None)


def _paint_torn_feather(cfg: ArtConfig, lay: Layout, card: np.ndarray,
                        rgb: np.ndarray, rough: np.ndarray, relief: np.ndarray,
                        W: int, H: int):
    """Feather the torn edge into base colour, roughness and relief."""
    floor_lin, ceil_lin = ink_floor(cfg)
    f = _torn_feather(cfg, lay, card, W, H) * 0.55
    col = np.array(torn_fibre_linear(cfg), np.float32)
    rgb = rgb * (1.0 - f[:, :, None]) + col[None, None, :] * f[:, :, None]
    rough = np.clip(rough + 0.055 * f, 0.30, 0.98)
    relief = relief + f * 0.010
    return (np.clip(rgb, floor_lin, ceil_lin).astype(np.float32),
            rough.astype(np.float32), relief.astype(np.float32))


def _composite(paper: dict, red: Ink, black: Ink,
               cfg: ArtConfig | None = None) -> tuple[np.ndarray, np.ndarray]:
    """Lay the ink on the sheet.  Red first, then black over it.

    Colour is resolved here, not when the mark was drawn: each layer's LOAD picks a
    point between its dry and wet albedo, so a starved stroke comes out pale and warm
    and a charged one comes out near-black, from the same geometry.
    """
    pal = palette_for(cfg)
    floor_lin, ceil_lin = ink_floor(cfg)
    rgb = paper["rgb"].copy()
    rough = paper["rough"].copy()

    def lay_ink(rgb, rough, ink: Ink, wet, dry, rw, rd):
        wet = np.array(wet, np.float32); dry = np.array(dry, np.float32)
        col = dry[None, None, :] + (wet - dry)[None, None, :] * ink.d[:, :, None]
        a = ink.a[:, :, None]
        rgb = rgb * (1.0 - a) + col * a
        rr = rd + (rw - rd) * ink.d
        rough = rough * (1.0 - ink.a) + rr * ink.a
        return rgb, rough

    rgb, rough = lay_ink(rgb, rough, red, pal.red_wet, pal.red_dry,
                         pal.rough_red_wet, pal.rough_red_dry)
    rgb, rough = lay_ink(rgb, rough, black, pal.black_wet, pal.black_dry,
                         pal.rough_black_wet, pal.rough_black_dry)

    # Ink sits ON an aged sheet, so the paper's own dirt shows through the thinner
    # marks - but only through the THIN ones.  Applied to the whole ink mask it pulled
    # the black core up off its floor everywhere the edge band reached, which is a third
    # of what kept the contrast at 11.7:1.  Weighted by (1 - load) it touches a starved
    # stroke and leaves a charged one alone.
    dirt = np.clip(paper["grime"] * 0.5 + paper["edge_band"] * 0.6, 0.0, 1.0)
    thin = np.maximum(red.a * (1.0 - red.d), black.a * (1.0 - black.d))
    rgb = rgb * (1.0 - 0.13 * dirt[:, :, None] * thin[:, :, None])
    return (np.clip(rgb, floor_lin, ceil_lin).astype(np.float32),
            np.clip(rough, 0.30, 0.98).astype(np.float32))


def _relief(paper: dict, red: Ink, black: Ink, cfg: ArtConfig, rng) -> np.ndarray:
    """Signed relief in MILLIMETRES for the normal bake.

    Study 6: fibre grain 0.010 - 0.020 mm on a 0.1 - 0.4 mm cell; two fold grooves 0.5 mm
    radius and 0.05 mm deep with a 1.5 mm wander; cockling depressions 0.02 - 0.05 mm
    along the heaviest strokes, because wet ink shrinks the sheet as it dries; two or
    three thumb dents.  Curl, folds and the dog-ear are GEOMETRY and are not here.
    """
    ppmm = cfg.px
    H, W = paper["rgb"].shape[:2]
    # THE FIBRE GRAIN, at the cell the study asks for and no coarser.
    #
    # The first pass put its high-frequency term at a 0.26 mm cell with a value-noise
    # lattice, whose dominant WAVELENGTH is about twice the cell: 0.52 mm, isotropic.
    # Banded slope-energy analysis of the shipped map found only 4 - 7 % of the slope
    # energy at or below the study's 0.4 mm fibre cell against 62 - 79 % in the
    # 0.4 - 1.5 mm band, and the raking close-up read as pebbled stucco.
    #
    # Two things fix it.  First the cell comes down to 0.20 mm across the fibre, which
    # is 2.6 texels at the shipping 12.923 px/mm - the finest cell a 2048 map can carry
    # without aliasing, and inside the study's 0.1 - 0.4 mm band.  Second it is made
    # ANISOTROPIC, 1.1 mm along the fibre against 0.20 mm across it, because kozo is
    # 10 - 15 mm of long fibre lying down in a sheet and isotropic bumps are plaster.
    across_mm, along_mm = 0.17, 0.70
    fibre_grain = noise(rng, H, W, max(1.5, along_mm * ppmm),
                        aniso=across_mm / along_mm) - 0.5
    # HIGH-PASSED.  Catmull-Rom value noise on a 2.2 px lattice peaks where it should
    # but drags a long low-frequency tail behind it, and that tail is most of what the
    # 0.4 - 1.5 mm band was measuring.  Subtracting a 0.9 mm blur leaves the fibre and
    # takes the pebble, which is exactly the separation the study's two cell sizes
    # describe.  The gain is set so the peak-to-peak relief lands in the study's
    # 0.010 - 0.020 mm band after the high pass, not before it.
    fibre_grain = fibre_grain - blur(fibre_grain, max(0.8, 0.45 * ppmm))
    z = fibre_grain * 0.020
    # a second, finer and weaker isotropic break-up so the lay is not a corduroy
    micro = noise(rng, H, W, max(1.5, 0.16 * ppmm)) - 0.5
    z += (micro - blur(micro, max(0.8, 0.40 * ppmm))) * 0.008
    # the visible long fibres are relief too, but they were the SPARSE STEEP term in
    # the first map (0.012 mm over a 0.07 mm stroke is a 10 deg wall), so they come down
    z += paper["fibre"] * 0.0030
    # the 1.7 mm blotch field used to carry most of the slope energy; it is a value
    # field, not a height field, and at 0.010 mm it was the pebble
    z += (paper["grain"]) * 0.0012
    # REFERENCE_SPEC row 24: the MESH carries a real 7 deg crease over a 2.2 mm half
    # width and the lighting shades it.  A 0.050 mm groove in the normal map on top of
    # that shades the same fold twice.  What is left here is only the fibre disturbance
    # a fold leaves in the sheet - an order of magnitude down, and no signed lip at all.
    z -= paper["crease"] * 0.0055
    z += paper["crease_signed"] * 0.0016
    heavy = blur(np.maximum(red.a, black.a), 0.55 * ppmm)
    z -= _smoothstep((heavy - 0.30) / 0.45) * 0.038          # cockling
    for k in range(3):
        r2 = _rng(cfg.seed, "dent%d" % k)
        dx = r2.uniform(6, CARD_W_MM - 6); dy = r2.uniform(10, CARD_H_MM - 10)
        rr = r2.uniform(3.0, 6.5)
        yy, xx = mm_grid(cfg, H, W)
        z -= np.exp(-(np.hypot(xx - dx, yy - dy) / rr) ** 2) * 0.020
    return z.astype(np.float32)


def build_front(cfg: ArtConfig | None = None, lay: Layout = LAYOUT) -> TagArt:
    """Draw the printed face.

    Order matters: the red goes down first, then the black over it, because the centre
    character is brushed ON the ring and the ring must show through where the black is
    thin.  The seals are stamped before the ring so the ring's lap can cross them.
    """
    cfg = cfg or ArtConfig()
    ppmm = cfg.px
    off = cfg.pad_mm
    W, H = raster_size(cfg)

    card, outline = _card_mask(cfg, lay, W, H)

    red = Ink(H, W)
    black = Ink(H, W)
    draw_rules(red, cfg, lay, W, H)
    dart_info = draw_corner_darts(black, red, cfg, lay, W, H)
    leaf_cov = draw_ornaments(red, cfg, lay, W, H, black=black)
    seal_info = draw_seals(red, cfg, lay, W, H)
    draw_ring(red, cfg, lay, W, H)
    draw_emblem(black, cfg, lay, W, H)
    # THE HERO GLYPH IS BUILT FIRST AND STAMPED LAST.  Built first so the columns can
    # be clipped out of it (REFERENCE_SPEC row 2 / section 7: the lower-right column
    # welded to 爆 in the second build); stamped last because 爆 is brushed ON the ring
    # and over the columns, which is the drawing order that has always been right.
    centre_cov, centre_meta, centre_rng = build_centre(cfg, lay, W, H)
    text_report = typeset(black, red, cfg, lay, W, H, seal_info, centre_cov=centre_cov)
    centre_meta = stamp_centre(black, centre_cov, centre_meta, centre_rng, cfg)
    # REFERENCE_SPEC row 17: the vermilion leaf pair is STAMPED, and a stamp goes on
    # after the writing.  Without this the lower-centre column simply paints over both
    # marks and only 4 % and 28 % of the red survives to be seen.
    if leaf_cov is not None and leaf_cov.any():
        black.knock_out(leaf_cov)

    ink_bleed(red, ppmm, _rng(cfg.seed, "bleed_red"), mm=0.17, strength=0.13)
    ink_bleed(black, ppmm, _rng(cfg.seed, "bleed_black"), mm=0.28, strength=0.30)

    paper = paper_ground(cfg, lay, W, H, card, side="front")
    rgb, rough = _composite(paper, red, black, cfg)
    relief = _relief(paper, red, black, cfg, _rng(cfg.seed, "relief_front"))
    rgb, rough, relief = _paint_torn_feather(cfg, lay, card, rgb, rough, relief, W, H)
    fringe = _fringe_field(cfg, lay, card, W, H)
    scorch = _scorch_field(cfg, lay, W, H)
    ink_mask = np.maximum(red.a, black.a)

    art = TagArt(
        side="front", ppmm=cfg.ppmm, width=W, height=H,
        base_colour=rgb, paper_rgb=paper["rgb"], roughness=rough, relief=relief,
        card_mask=card, fringe=fringe, scorch=scorch, ink_mask=ink_mask,
        ink_black=black, ink_red=red, outline_mm=outline,
    )
    art.report = {
        "text": text_report, "centre": centre_meta, "seals": seal_info,
        "ornaments": dart_info, "pad_mm": off, "supersample": cfg.supersample,
        "ink_floor": cfg.ink_floor,
    }
    if cfg.supersample > 1:
        art = _downsample(art, cfg.supersample)
    return art


def build_back(cfg: ArtConfig | None = None, lay: Layout = LAYOUT,
               front: TagArt | None = None) -> TagArt:
    """Draw the back: blank aged paper, plus a faint mirrored show-through of the print.

    80 g/m2 kozo is noticeably translucent, so the back of a real printed fuda carries a
    ghost of its own face.  The ghost is MIRRORED in x (you turned the card over about
    its long axis), blurred by the sheet's own thickness and scattered, and it never gets
    anywhere near ink values - it is a slightly warmer, slightly darker paper.
    """
    cfg = cfg or ArtConfig()
    ppmm = cfg.px
    off = cfg.pad_mm
    W, H = raster_size(cfg)
    card, outline = _card_mask(cfg, lay, W, H)

    bcfg = ArtConfig(**{**cfg.__dict__, "seed": cfg.seed ^ 0x5F5E1})
    paper = paper_ground(bcfg, lay, W, H, card, side="back", sheet_seed=cfg.seed)
    rgb = paper["rgb"].copy()
    rough = paper["rough"].copy()

    ghost = np.zeros((H, W), np.float32)
    if front is not None and front.ink_mask is not None:
        # TWO ghosts, not one.  Sumi soaks into the sheet and vermilion sits on it, so
        # the black print shows through more readily - but the first pass ran the red
        # at 0.32 of the black and desaturated both to the same grey-sepia, which left
        # the most OPAQUE thing on the card, a 14 x 22 mm solid vermilion panel, as one
        # of the faintest ghosts while thin black strokes registered strongly.  Backwards.
        # Each ink now ghosts with its own weight and its own tint, and the blur is a
        # full 0.9 mm - scattering through 0.15 mm of kozo is what makes a show-through
        # read as translucency rather than as a reduced-opacity copy.
        nrng = _rng(cfg.seed, "ghost")
        fibre_break = 0.72 + 0.56 * noise(nrng, H, W, max(1.8, 1.1 * ppmm))
        layers = []
        if front.ink_black is not None:
            layers.append((front.ink_black.a, (0.45, 0.40, 0.32), 1.00))
            layers.append((front.ink_red.a, (0.66, 0.47, 0.42), 0.72))
        else:
            layers.append((front.ink_mask, (0.45, 0.40, 0.32), 1.00))
        for src, tint_rgb, weight in layers:
            if src.shape != (H, W):
                src = _resize_bilinear(src, H, W)
            g = np.ascontiguousarray(src[:, ::-1])
            g = blur(g, max(0.7, 0.95 * ppmm))
            g = np.clip(g, 0.0, 1.0) * cfg.show_through * weight * fibre_break
            g = np.clip(g, 0.0, 1.0).astype(np.float32)
            tint = np.array(tint_rgb, np.float32)
            rgb = rgb * (1.0 - g[:, :, None]) + (rgb * tint[None, None, :]) * g[:, :, None]
            rough = rough + 0.02 * g
            ghost = np.maximum(ghost, g)

    relief = _relief(paper, Ink(H, W), Ink(H, W), bcfg, _rng(cfg.seed, "relief_back"))
    relief = relief - ghost * 0.010          # the sheet cockled from the other side
    rgb, rough, relief = _paint_torn_feather(bcfg, lay, card,
                                             np.clip(rgb, *ink_floor(cfg)),
                                             rough, relief, W, H)
    fringe = _fringe_field(cfg, lay, card, W, H)
    scorch = _scorch_field(cfg, lay, W, H)

    art = TagArt(
        side="back", ppmm=cfg.ppmm, width=W, height=H,
        base_colour=np.clip(rgb, *ink_floor(cfg)).astype(np.float32),
        paper_rgb=paper["rgb"], roughness=np.clip(rough, 0.30, 0.98).astype(np.float32),
        relief=relief, card_mask=card, fringe=fringe, scorch=scorch,
        ink_mask=ghost.astype(np.float32), outline_mm=outline,
    )
    art.report = {"show_through": cfg.show_through, "pad_mm": off}
    if cfg.supersample > 1:
        art = _downsample(art, cfg.supersample)
    return art


def _down(a: np.ndarray, s: int) -> np.ndarray:
    H, W = a.shape[:2]
    H2, W2 = H // s, W // s
    a = a[:H2 * s, :W2 * s]
    if a.ndim == 2:
        return a.reshape(H2, s, W2, s).mean(axis=(1, 3)).astype(np.float32)
    return a.reshape(H2, s, W2, s, a.shape[2]).mean(axis=(1, 3)).astype(np.float32)


def _downsample(art: TagArt, s: int) -> TagArt:
    for name in ("base_colour", "paper_rgb", "roughness", "relief",
                 "card_mask", "fringe", "scorch", "ink_mask"):
        setattr(art, name, _down(getattr(art, name), s))
    for name in ("ink_black", "ink_red"):
        lyr = getattr(art, name)
        if lyr is not None:
            lyr.a = _down(lyr.a, s)
            lyr.d = _down(lyr.d, s)
    art.height, art.width = art.base_colour.shape[:2]
    return art


