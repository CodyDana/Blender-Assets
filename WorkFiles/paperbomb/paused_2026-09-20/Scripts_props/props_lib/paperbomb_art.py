def measure_ring(art: TagArt, cfg: ArtConfig, lay: Layout = LAYOUT) -> dict:
    """The study's own two ring gates, re-measured on what we actually drew.

    Study 5.2 measured the guide's ring at 97 % of 2 degree bins present, with two or
    three true gaps, and ink filling 15 % of the ring's own bounding box.  Those two
    numbers together are what separate a dry brush lap from a drawn annulus: high
    angular presence, low area fill.  A ring that is 97 % present AND 30 % full is a
    solid ellipse; one that is 60 % present is a broken circle, not a brush stroke.
    """
    if art.ink_red is None:
        return {}
    ppm = art.ppmm
    pad = cfg.pad_mm
    cx, cy = P(*lay.ring_centre)
    ow, oh = lay.ring_outer_mm
    a = art.ink_red.a
    H, W = a.shape

    def px(xm, ym):
        return ((xm + pad) * ppm), ((ym + pad) * ppm)

    x0, y0 = px(cx - ow * 0.5, cy - oh * 0.5)
    x1, y1 = px(cx + ow * 0.5, cy + oh * 0.5)
    box = a[max(0, int(y0)):min(H, int(y1)), max(0, int(x0)):min(W, int(x1))]
    fill = float((box > 0.5).mean()) if box.size else 0.0

    hit = 0
    bins = 180
    for k in range(bins):
        th = math.radians(k * 2.0)
        found = False
        for r in np.linspace(0.76, 1.16, 33):
            xm = cx + (ow * 0.5 - lay.ring_stroke_mm[1] * 0.55) * r * math.cos(th)
            ym = cy - (oh * 0.5 - lay.ring_stroke_mm[1] * 0.55) * r * math.sin(th)
            ix, iy = px(xm, ym)
            ix, iy = int(ix), int(iy)
            if 0 <= iy < H and 0 <= ix < W and a[iy, ix] > 0.5:
                found = True
                break
        hit += int(found)
    return {"ring_ink_fill_of_bbox": round(fill, 4),
            "ring_angular_coverage": round(hit / bins, 3),
            "study_targets": {"ink_fill_of_bbox": 0.152, "angular_coverage": 0.972}}


def _measure(art: TagArt, lay: Layout = LAYOUT) -> dict:
    """The few numbers worth checking against the study after every change."""
    card = art.card_mask > 0.5
    bc = art.base_colour
    srgb = linear_to_srgb(bc)
    luma = (0.2126 * srgb[:, :, 0] + 0.7152 * srgb[:, :, 1] + 0.0722 * srgb[:, :, 2])[card]
    out = {
        "size_px": [art.width, art.height],
        "stored_luma_p05": round(float(np.percentile(luma, 5)), 3),
        "stored_luma_p50": round(float(np.percentile(luma, 50)), 3),
        "stored_luma_p99": round(float(np.percentile(luma, 99)), 3),
        "linear_luma_p50": round(float(np.percentile(
            (0.2126 * bc[:, :, 0] + 0.7152 * bc[:, :, 1] + 0.0722 * bc[:, :, 2])[card], 50)), 3),
    }
    if art.ink_black is not None:
        area = float(card.sum())
        out["ink_black_coverage"] = round(float((art.ink_black.a[card] > 0.5).sum() / area), 4)
        out["ink_red_coverage"] = round(float((art.ink_red.a[card] > 0.5).sum() / area), 4)
        out["ink_total_coverage"] = round(
            float((np.maximum(art.ink_black.a, art.ink_red.a)[card] > 0.5).sum() / area), 4)
    return out


def main(argv: Sequence[str] | None = None) -> int:
    if argv is None:
        argv = sys.argv[sys.argv.index("--") + 1:] if "--" in sys.argv else []
    ap = argparse.ArgumentParser(description="Draw the paper bomb's artwork.")
    ap.add_argument("--out", default=os.path.join(PROJECT_ROOT, "WorkFiles", "paperbomb", "art"))
    ap.add_argument("--ppmm", type=float, default=12.923)
    ap.add_argument("--seed", type=int, default=20260919)
    ap.add_argument("--ss", type=int, default=1)
    ap.add_argument("--wear", type=float, default=1.0)
    ap.add_argument("--tag", default="preview")
    ap.add_argument("--no-back", action="store_true")
