_GLYPH_CACHE: dict = {}
_CMAP_CACHE: dict = {}


def font_codepoints(font_path: str) -> set[int]:
    """Every code point the font's ``cmap`` maps, read from the .ttf itself.

    Blender will happily typeset a character the font does not have: FreeType hands
    back glyph 0, which is a .notdef box, and ``to_curve`` returns its outline like any
    other.  A box on the tag would be a fabricated character - precisely what the study
    forbids - and nothing downstream would notice.  So coverage is decided here, from
    the font binary, before anything is drawn.  Formats 4 and 12 only; that is what
    both project fonts carry.
    """
    if font_path in _CMAP_CACHE:
        return _CMAP_CACHE[font_path]
    with open(font_path, "rb") as f:
        head = f.read(12)
        if len(head) < 12:
            raise RuntimeError("not a font file: %s" % font_path)
        num_tables = struct.unpack(">H", head[4:6])[0]
        dirs = f.read(16 * num_tables)
        cmap_off = cmap_len = 0
        for i in range(num_tables):
            tag, _chk, off, ln = struct.unpack(">4sIII", dirs[16 * i:16 * i + 16])
            if tag == b"cmap":
                cmap_off, cmap_len = off, ln
                break
        if not cmap_off:
            raise RuntimeError("font has no cmap table: %s" % font_path)
        f.seek(cmap_off)
        blob = f.read(cmap_len)

    n = struct.unpack(">H", blob[2:4])[0]
    best = None
    best_rank = -1
    for i in range(n):
        pid, eid, off = struct.unpack(">HHI", blob[4 + 8 * i:12 + 8 * i])
        if off + 2 > len(blob):
            continue
        fmt = struct.unpack(">H", blob[off:off + 2])[0]
        # unicode full repertoire beats BMP; anything beats a legacy table
        rank = {12: 3, 4: 2}.get(fmt, 0)
        if (pid, eid) in ((3, 10), (0, 4), (0, 6)):
            rank += 1
        if rank > best_rank:
            best, best_rank = (fmt, off), rank
    if best is None:
        raise RuntimeError("font has no usable cmap subtable: %s" % font_path)

    fmt, off = best
    cps: set[int] = set()
    if fmt == 12:
        ngroups = struct.unpack(">I", blob[off + 12:off + 16])[0]
        base = off + 16
        for g in range(ngroups):
            s, e, _gid = struct.unpack(">III", blob[base + 12 * g:base + 12 * g + 12])
            if e - s > 0x20000:
                continue
            cps.update(range(s, e + 1))
    elif fmt == 4:
        segx2 = struct.unpack(">H", blob[off + 6:off + 8])[0]
        seg = segx2 // 2
        ends = struct.unpack(">%dH" % seg, blob[off + 14:off + 14 + segx2])
        sstart = off + 16 + segx2
        starts = struct.unpack(">%dH" % seg, blob[sstart:sstart + segx2])
        for s, e in zip(starts, ends):
            if e == 0xFFFF and s == 0xFFFF:
                continue
            cps.update(range(s, e + 1))
    else:
        raise RuntimeError("unsupported cmap format %d in %s" % (fmt, font_path))
    _CMAP_CACHE[font_path] = cps
    return cps


def _require_bpy():
    try:
        import bpy  # noqa: F401
    except ImportError as exc:      # pragma: no cover
        raise RuntimeError(
            "paperbomb_art needs Blender's Python for the font outlines.  Run it as\n"
            '  blender -b --factory-startup --python Scripts/props/props_lib/paperbomb_art.py'
        ) from exc
    return sys.modules["bpy"]


def glyph_outline(ch: str, font_path: str = FONT_PRIMARY, res: int = 10):
    """Outline contours of one character, in em units, plus its metrics.

    Returns ``(contours, meta)`` where each contour is an (N, 2) array with y UP and the
    origin on the baseline at the glyph's left side bearing, and ``meta`` carries the
    advance and the ink box.  Everything is divided by the advance, so one unit IS the
    em square and a caller sets a size in millimetres directly.

    A character the font does not cover raises ``MissingGlyph``.  There is no fallback
    box and nothing is ever drawn by hand.
    """
    key = (ch, font_path, res)
    if key in _GLYPH_CACHE:
        return _GLYPH_CACHE[key]
    if ord(ch) not in font_codepoints(font_path):
        raise MissingGlyph(
            "%s does not map U+%04X - the build stops here rather than let FreeType "
            "hand back a .notdef box and print it as a character"
            % (os.path.basename(font_path), ord(ch)))
    bpy = _require_bpy()

    fkey = ("__font__", font_path)
    if fkey in _GLYPH_CACHE:
        font = _GLYPH_CACHE[fkey]
    else:
        if not os.path.isfile(font_path):
            raise RuntimeError("font not found: %s" % font_path)
        font = bpy.data.fonts.load(font_path)
        _GLYPH_CACHE[fkey] = font

    def _outline(body):
        cu = bpy.data.curves.new("_pb_glyph", type="FONT")
        cu.body = body
        cu.font = font
        cu.size = 1.0
        cu.align_x = "LEFT"
        cu.align_y = "TOP_BASELINE"
        cu.resolution_u = res
        ob = bpy.data.objects.new("_pb_glyph", cu)
        bpy.context.scene.collection.objects.link(ob)
        try:
            dg = bpy.context.evaluated_depsgraph_get()
            crv = ob.to_curve(dg)
            out = []
            for sp in crv.splines:
                if sp.type == "BEZIER":
                    bp = sp.bezier_points
                    n = len(bp)
                    if n < 2:
                        continue
                    segs = n if sp.use_cyclic_u else n - 1
                    chunk = []
                    for i in range(segs):
                        a, b = bp[i], bp[(i + 1) % n]
                        chunk.append(bezier(a.co[:2], a.handle_right[:2],
                                            b.handle_left[:2], b.co[:2], res)[:-1])
                    out.append(np.concatenate(chunk, axis=0))
                else:
                    pts = np.array([p.co[:2] for p in sp.points], np.float64)
                    if len(pts) >= 3:
                        out.append(pts)
            ob.to_curve_clear()
        finally:
            bpy.data.objects.remove(ob)
            bpy.data.curves.remove(cu)
        return out

    one = _outline(ch)
    if not one:
        raise MissingGlyph(
            "font %s has no drawable glyph for U+%04X - the build stops here rather than "
            "improvise a character" % (os.path.basename(font_path), ord(ch)))
    two = _outline(ch + ch)
    a1 = np.concatenate(one, axis=0)
    a2 = np.concatenate(two, axis=0)
    advance = float(a2[:, 0].max() - a1[:, 0].max())
    if advance <= 1e-6:
        raise MissingGlyph("zero advance for U+%04X" % ord(ch))
    contours = [c / advance for c in one]
    allp = a1 / advance
    meta = {
        "codepoint": "U+%04X" % ord(ch),
        "contours": len(contours),
        "points": int(len(allp)),
        "ink_x": (float(allp[:, 0].min()), float(allp[:, 0].max())),
        "ink_y": (float(allp[:, 1].min()), float(allp[:, 1].max())),
    }
    _GLYPH_CACHE[key] = (contours, meta)
    return contours, meta


def verify_font_coverage(font_path: str = FONT_PRIMARY) -> dict:
    """Every configured character must resolve to a real glyph.  Loud failure or nothing.

    Checked twice over: the code point must be in the font's own cmap, and the outline
    that comes back must have contours.  A character that fails either is a hard stop.
    """
    cps = font_codepoints(font_path)
    seen: dict[str, dict] = {}
    for _slot, s in TEXT:
        for ch in s:
            key = "U+%04X" % ord(ch)
            if key not in seen:
                _, meta = glyph_outline(ch, font_path)
                seen[key] = meta
    return {"font": os.path.basename(font_path), "cmap_codepoints": len(cps),
            "distinct": len(seen), "glyphs": seen}


