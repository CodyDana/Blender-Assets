def seal_keepout(cfg: ArtConfig, lay: Layout, W: int, H: int) -> np.ndarray:
    """1.0 where ornament ink may print, 0.0 inside either chop's box plus a margin.

    REFERENCE_SPEC row 20.  Both chops are stamped on clear paper in the guides; ours
    had the bottom-left corner bracket running up through the big seal's frame, which
    fused the two into one red component 4.7 mm taller than the row allows.  Measured
    on the drawing LAYER the seal was fine; measured on the red raster - which is what
    a camera and an independent pass both see - it was not.  The keep-out is applied to
    the ornaments, never to the chop, because it is the chop's box that is specified.
    """
    yy, xx = mm_grid(cfg, H, W)
    k = float(lay.seal_keepout_mm)
    keep = np.ones((H, W), np.float32)
    for fx, fy in ((lay.big_seal_frame_x, lay.big_seal_frame_y),
                   (lay.small_seal_frame_x, lay.small_seal_frame_y)):
        bx0, by0 = P(fx[0], fy[0])
        bx1, by1 = P(fx[1], fy[1])
        inside = ((xx >= bx0 - k) & (xx <= bx1 + k)
                  & (yy >= by0 - k) & (yy <= by1 + k))
        keep = np.where(inside, 0.0, keep).astype(np.float32)
    return keep


def _mask_window(win: "Window | None", keep: np.ndarray) -> "Window | None":
    """Multiply a brush window by a full-raster keep mask, in place."""
    if win is None:
        return None
    h_, w_ = win.shape
    win.cov[...] = win.cov * keep[win.y0:win.y0 + h_, win.x0:win.x0 + w_]
    return win


def draw_rules(red: Ink, cfg: ArtConfig, lay: Layout, W: int, H: int) -> None:
    """ONE red rule per side, ruled with a brush, plus four hooked corner brackets.

    REFERENCE_SPEC rows 4, 21 and 22, and worklist 4, 18 and 19.  Three things changed
    against the first build and each one is measured:

    * **One rule per side.**  Both guides carry exactly one, verified twice in the spec.
      Ours ran a second full-width line on the top and bottom, and a double frame against
      a single one changes the whole read at thumbnail size.  ``inner_rule_sides`` is now
      empty; the brackets still ride on the inner offset, which is where the eye goes.
    * **Weight.**  0.57 - 0.68 mm on the four sides, not 1.00 - and *symmetric*: our right
      rule measured 63 % heavier than our left because every lap drew its own breath
      profile and the mean of eighty samples of a two-octave field is not a stable number.
      Each profile is now normalised to a mean of exactly 1.0 before the landing swell, so
      a lap's WIDTH varies along itself and its AVERAGE does not vary between laps.
    * **Continuity.**  The reference's rules run out of ink: occupancy 0.82 - 0.92 with
      7 - 12 breaks per side, the longest 1.9 - 3.9 mm.  Ours measured occupancy 1.00 top
      and bottom - an unbroken line of constant width is the most machine-made thing on
      the card.  Note also that ours had it backwards: our PATH wobbled 4 - 10x more than
      the reference's while our WIDTH varied less, so the wander comes down and the width
      swing goes up.
    """
    rng = _rng(cfg.seed, "rules")
    x0, y0, x1, y1 = _frame_box(lay)
    wgt = lay.rule_weight_mm

    def ruled(p0, p1, weight, load0=1.0, dry=0.30, ragged=0.46, swell=1.45,
              breaks=(7, 12), occupancy=RULE_OCCUPANCY_TARGET):
        """One ruled line, but ruled with a brush that runs out of ink."""
        p0 = np.array(p0, np.float64); p1 = np.array(p1, np.float64)
        L = float(np.hypot(*(p1 - p0)))
        p = np.linspace(0.0, 1.0, max(48, int(L * 3)))[:, None] * (p1 - p0) + p0
        # 0.014 mm, not 0.055: the reference's rules are STRAIGHT and unevenly weighted,
        # ours were wavy and evenly weighted
        p = wander(p, rng, 0.014, 15.0)
        t = np.linspace(0.0, 1.0, 80)
        # THE BREATH IS FASTER AND THE PROFILE IS NORMALISED ON ITS MEDIAN.  Two
        # separate stability bugs, both found by moving the occupancy target by 0.01 and
        # watching the four sides' weights jump from 0.66 - 0.67 to 0.46 - 0.68 and the
        # left-right difference from 0.03 to 0.16.  (1) A 9-sample cell over 80 samples
        # is about nine independent lobes per lap, and the MEDIAN of nine lobes is not a
        # determined number - the sides were sampling their own noise.  4.5 doubles the
        # lobes, which is also a faster width change along the lap and closer to a
        # brush.  (2) REFERENCE_SPEC row 21 is measured as a per-scanline MEDIAN, so the
        # profile is normalised on its median: normalising the MEAN leaves the median
        # free to wander with the shape of the field, which is exactly what it did.
        breath = noise(rng, 1, 80, 4.5)[0]
        # the swing is 0.70 - 1.32 about 1, not 0.56 - 1.44: at the thin end of the wider
        # swing a 0.60 mm rule drew 0.34 mm, which on a 12.9 px/mm map is four texels of
        # half-covered ink and measures as a BREAK on any threshold-based occupancy.
        # The weight still varies along the lap; it no longer disappears.
        prof = 0.70 + 0.62 * breath
        prof = prof / max(float(np.median(prof)), 1e-6)   # <- what makes L and R agree
        prof = prof * (1.0 + (swell - 1.0) * np.exp(-((t - 0.030) / 0.055) ** 2))
        prof = prof * (1.0 - 0.22 * _smoothstep((t - 0.94) / 0.06))
        ld = load0 * (0.82 + 0.18 * np.roll(breath, 23))
        win = brush_stroke(p, weight * prof, cfg=cfg, rng=rng, W=W, H=H,
                           load=ld, dry=dry, bristle_mm=0.16, streak_cell_mm=5.0,
                           edge_ragged=ragged, step_mm=0.35,
                           gaps=_rule_breaks(rng, L, breaks, occupancy),
                           gap_soft_mm=RULE_GAP_SOFT_MM)
        return win

    def _rule_breaks(r, length_mm, count, occupancy):
        """Places a brush lifted, as arclength fractions, to a TARGET OCCUPANCY.

        REFERENCE_SPEC row 22: occupancy 0.82 - 0.95 per side with 7 - 12 breaks, the
        longest 1.9 - 3.9 mm.  The second build drew each gap from a fixed 0.5 - 2.8 mm
        range, which is a different occupancy on every side because the sides are
        different lengths: eight gaps averaging 1.65 mm cost 21 % of a 62 mm top rule and
        only 9 % of a 142 mm side, and the top and bottom rules duly measured 0.71 - 0.79
        against a 0.82 floor.  The BUDGET is set first, then shared out unevenly so the
        rhythm is still a brush's and not a dashed line.

        NON-OVERLAPPING and never adjacent: two gaps that land on top of each other read
        as one long hole, which is the one thing a ruled border must not have.
        """
        if length_mm < 8.0 or not count:
            return ()
        n = int(r.integers(count[0], count[1] + 1))
        # ...and each lift costs more than the lift itself: the brush thins into a gap
        # and out of it, so a 0.8 mm drawn break measures about 1.3 mm of bare rule.
        # Measured over the four sides at 0.5 mm per break, so the BUDGET is what the
        # rule actually loses and not what was asked for.
        budget = max(0.0, 1.0 - float(occupancy)) * length_mm - RULE_BREAK_EDGE_MM * n
        wts = r.uniform(0.45, 1.95, n)
        lens = np.clip(budget * wts / float(wts.sum()), 0.30, 3.60)
        out: list[tuple[float, float]] = []
        for gap_mm in lens:
            gap = float(gap_mm) / length_mm
            keep = 2.2 / length_mm          # 2.2 mm of ink between any two breaks
            for _ in range(24):
                s0 = float(r.uniform(0.02, 0.98 - gap))
                if any(s0 < b + keep and a - keep < s0 + gap for a, b in out):
                    continue
                out.append((s0, s0 + gap))
                break
        return tuple(out)

    # --- outer rule, broken either side of the mid-side lozenge.
    # REFERENCE_SPEC's one-more-reading: the four reds on the sheet are ONE pigment at
    # four laid-on WEIGHTS - hue spread 1.1 deg, saturation spread 0.021, but value
    # spread 0.139 - and the border is the HEAVIEST red on the card.  We shipped all four
    # at one weight (value spread 0.008) with the border our LIGHTEST.  The rules now
    # carry the most ink of anything red here; the ring and the seals carry less.
    gy0, gy1 = lay.side_break_y[0] * CARD_H_MM, lay.side_break_y[1] * CARD_H_MM
    red.stamp(ruled((x0, y0), (x1, y0), wgt, load0=1.0, dry=0.07, breaks=(5, 8)))
    red.stamp(ruled((x1, y1), (x0, y1), wgt, load0=1.0, dry=0.07, breaks=(5, 8)))
    red.stamp(ruled((x0, y0), (x0, gy0), wgt, load0=1.0, dry=0.07, breaks=(4, 6)))
    red.stamp(ruled((x0, gy1), (x0, y1), wgt, load0=1.0, dry=0.07, breaks=(4, 6)))
    red.stamp(ruled((x1, y0), (x1, gy0), wgt, load0=1.0, dry=0.07, breaks=(4, 6)))
    red.stamp(ruled((x1, gy1), (x1, y1), wgt, load0=1.0, dry=0.07, breaks=(4, 6)))

    # --- inner rule: present at the corners, starved away mid-span
    o = lay.inner_rule_offset_mm
    ix0, iy0, ix1, iy1 = x0 + o, y0 + o, x1 - o, y1 - o
    run = lay.inner_rule_corner_run_mm

    def inner(p0, p1):
        p0 = np.array(p0, np.float64); p1 = np.array(p1, np.float64)
        L = float(np.hypot(*(p1 - p0)))
        n = max(24, int(L * 2))
        p = np.linspace(0.0, 1.0, n)[:, None] * (p1 - p0) + p0
        p = wander(p, rng, 0.06, 13.0)
        t = np.linspace(0.0, 1.0, 64)
        d = np.minimum(t, 1.0 - t) * L
        # full at the corners, gone in the middle of a long run
        keep = 1.0 - _smoothstep((d - run * 0.55) / (run * 0.55))
        ld = 0.42 + 0.58 * keep
        wid = lay.inner_rule_weight_mm * (0.42 + 0.58 * keep) * (0.85 + 0.30 * noise(rng, 1, 64, 8.0)[0])
        return brush_stroke(p, wid, cfg=cfg, rng=rng, W=W, H=H, load=ld,
                            dry=0.34, bristle_mm=0.22, streak_cell_mm=2.4, edge_ragged=0.42)

    runs = {"top": ((ix0, iy0), (ix1, iy0)), "bottom": ((ix1, iy1), (ix0, iy1)),
            "left": ((ix0, iy0), (ix0, iy1)), "right": ((ix1, iy0), (ix1, iy1))}
    # the two chops are keep-out zones for every piece of ornament work (row 20)
    keep = seal_keepout(cfg, lay, W, H)
    for side in lay.inner_rule_sides:
        red.stamp(_mask_window(inner(*runs[side]), keep))

    # --- hooked corner brackets: one confident L per corner, drawn in a single lap
    # from the end of the long leg, round the knee and out along the short one, with a
    # small inward curl at each terminal.  They ride ON the inner rule's corner, which
    # is what doubles the border where the eye looks and nowhere else.
    for sx, sy, cx_, cy_ in ((1, 1, ix0, iy0), (-1, 1, ix1, iy0),
                             (1, -1, ix0, iy1), (-1, -1, ix1, iy1)):
        # the bottom pair is short: both seal boxes sit inside where a 14 mm leg would
        # run, and five near-parallel reds in a 6 mm span read as a registration error
        lv = lay.bracket_leg_v_mm if sy > 0 else lay.bracket_leg_v_bottom_mm
        lh = lay.bracket_leg_h_mm if sy > 0 else lay.bracket_leg_h_bottom_mm
        curl = lay.bracket_curl_mm if sy > 0 else lay.bracket_curl_bottom_mm
        start = bezier((cx_ + sx * curl * 0.75, cy_ + sy * (lv + curl * 0.55)),
                       (cx_ + sx * curl * 0.62, cy_ + sy * (lv + curl * 0.15)),
                       (cx_ - sx * curl * 0.18, cy_ + sy * (lv + curl * 0.10)),
                       (cx_, cy_ + sy * lv), 20)
        run_v = np.stack([np.full(48, cx_),
                          np.linspace(cy_ + sy * lv, cy_ + sy * curl, 48)], axis=1)
        knee = bezier((cx_, cy_ + sy * curl), (cx_, cy_ + sy * curl * 0.18),
                      (cx_ + sx * curl * 0.18, cy_), (cx_ + sx * curl, cy_), 20)
        run_h = np.stack([np.linspace(cx_ + sx * curl, cx_ + sx * lh, 40),
                          np.full(40, cy_)], axis=1)
        end = bezier((cx_ + sx * lh, cy_),
                     (cx_ + sx * (lh + curl * 0.55), cy_ - sy * curl * 0.06),
                     (cx_ + sx * (lh + curl * 0.72), cy_ - sy * curl * 0.62),
                     (cx_ + sx * (lh + curl * 0.20), cy_ - sy * curl * 0.78), 20)
        path = wander(join(start, run_v, knee, run_h, end), rng, 0.05, 8.0)
        t = np.linspace(0.0, 1.0, 72)
        # thin into each curl, heaviest through the knee
        wid = lay.bracket_weight_mm * (0.34
                                       + 0.72 * _smoothstep((t - 0.03) / 0.12)
                                       * (1.0 - _smoothstep((t - 0.86) / 0.12))
                                       + 0.34 * np.exp(-((t - 0.52) / 0.16) ** 2))
        wid *= 0.88 + 0.26 * noise(rng, 1, 72, 9.0)[0]
        red.stamp(_mask_window(
            brush_stroke(path, wid, cfg=cfg, rng=rng, W=W, H=H,
                         load=0.94 - 0.18 * t, dry=0.24, bristle_mm=0.16,
                         streak_cell_mm=2.4, edge_ragged=0.38, step_mm=0.26), keep))


def draw_corner_darts(black: Ink, red: Ink, cfg: ArtConfig, lay: Layout,
                      W: int, H: int) -> dict:
    """The 2.1 mm dart that carries each corner OUTBOARD of the top and bottom rules.

    REFERENCE_SPEC row 14 / worklist 13, measured tolerance-free: "outboard" is ink lying
    outside the fitted rule rectangle, so it needs no threshold, and both guides put
    2.0 - 2.2 mm of ornament past the top and bottom rules at ALL FOUR corners.  Our side
    -rule overshoot (0.57 - 0.97 mm) was already right; only the horizontal dart was
    missing, and every pixel of our outside-the-rule ink was RED where the reference mixes
    a red flourish with a BLACK dart.  Section 7 adds the part no number carries: the
    reference's hook curls inboard like a comma turning down-and-in, with the ink pooling
    darkest where the two rules cross.
    """
    rng = _rng(cfg.seed, "corner_darts")
    x0, y0, x1, y1 = _frame_box(lay)
    out = lay.corner_dart_mm
    run = lay.corner_dart_run_mm
    wgt = lay.corner_dart_weight_mm
    drawn = []
    for sx, sy, cx_, cy_ in ((1, 1, x0, y0), (-1, 1, x1, y0),
                             (1, -1, x0, y1), (-1, -1, x1, y1)):
        # a short lap that starts OUTSIDE the corner, drives in along the horizontal
        # rule and turns down-and-in at the end: the comma, drawn as one stroke.
        # "Outboard" is measured PERPENDICULAR to the top/bottom rule, so the tip has to
        # clear it in y by the full 2.1 mm, not along the diagonal.
        # A COMMA, NOT A WHISKER.  The first version ran the hook 7.5 mm in along the
        # rule and read as an antenna growing out of each corner; the reference's dart
        # is a short mark that pools where the two rules cross and turns down-and-in
        # over about three millimetres.
        tip = (cx_ - sx * out * 0.52, cy_ - sy * (out + wgt * 0.30))
        knee = (cx_ + sx * run * 0.30, cy_ + sy * 0.16)
        hook = bezier((cx_ + sx * run * 0.30, cy_ + sy * 0.16),
                      (cx_ + sx * run * 0.62, cy_ + sy * 0.34),
                      (cx_ + sx * run * 0.74, cy_ + sy * 0.74),
                      (cx_ + sx * run * 0.44, cy_ + sy * 1.02), 18)
        path = join(np.stack([np.linspace(tip[0], knee[0], 30),
                              np.linspace(tip[1], knee[1], 30)], axis=1), hook)
        path = wander(path, rng, 0.030, 4.0)
        t = np.linspace(0.0, 1.0, 48)
        # thin at the outboard tip, pooling darkest where the two rules cross, thin
        # again into the curl
        wid = wgt * (0.20 + 1.20 * _smoothstep((t - 0.06) / 0.22)
                     * (1.0 - 0.76 * _smoothstep((t - 0.68) / 0.32))
                     + 0.62 * np.exp(-((t - 0.46) / 0.15) ** 2))
        black.stamp(brush_stroke(path, wid, cfg=cfg, rng=rng, W=W, H=H,
                                 load=1.0 - 0.22 * t, dry=0.12, bristle_mm=0.14,
                                 streak_cell_mm=1.8, edge_ragged=0.32, step_mm=0.18,
                                 core=0.35))
        # ...AND THE RED FLOURISH BESIDE IT.  Row 14's own words are that the reference
        # "MIXES a red flourish with a BLACK dart" at all four corners.  The first build
        # put every outboard texel in red; the second put every one in black, which is
        # one single-colour answer swapped for another.  This is the other half: a short
        # vermilion flick a couple of millimetres along the rule from the dart, crossing
        # it and carrying the same distance past.  It is deliberately lighter than the
        # dart - the black mark is the one that reads.
        fl = lay.corner_flourish_mm
        if fl > 0.0:
            at = cx_ + sx * lay.corner_flourish_along_mm
            p = bezier((at - sx * 0.30, cy_ + sy * 1.15),
                       (at + sx * 0.10, cy_ + sy * 0.30),
                       (at + sx * 0.34, cy_ - sy * (fl * 0.55)),
                       (at + sx * 0.18, cy_ - sy * fl), 24)
            p = wander(p, rng, 0.020, 3.0)
            tt = np.linspace(0.0, 1.0, 30)
            fw = lay.corner_flourish_weight_mm * (0.30 + 0.80 * _smoothstep((tt - 0.05) / 0.25)
                                                  * (1.0 - 0.72 * _smoothstep((tt - 0.55) / 0.45)))
            red.stamp(brush_stroke(p, fw, cfg=cfg, rng=rng, W=W, H=H,
                                   load=0.96 - 0.20 * tt, dry=0.14, bristle_mm=0.12,
                                   streak_cell_mm=1.6, edge_ragged=0.34, step_mm=0.16,
                                   core=0.40))
        drawn.append({"corner": [round(cx_, 2), round(cy_, 2)],
                      "outboard_mm": round(out, 2),
                      "flourish_outboard_mm": round(fl, 2)})
    return {"corner_darts": drawn, "outboard_mm": out,
            "colour": "black dart + red flourish",
            "flourish_outboard_mm": lay.corner_flourish_mm}


def draw_ornaments(red: Ink, cfg: ArtConfig, lay: Layout, W: int, H: int,
                   black: Ink | None = None) -> np.ndarray:
    """Lozenges and diamonds: small stamped marks, each one a little out of true.

    REFERENCE_SPEC rows 16, 17 and 18 / worklist 14, 15 and 20.  The centre chain gains
    its bottom link - a BLACK diamond sitting on the bottom rule at (35.05, 148.0) mm,
    2.39 x 3.62 - and the flanking leaf pair low on the card; and it loses the red leaf we
    put at (35.0, 3.5), because there is NOTHING above the top rule in either guide.
    """
    rng = _rng(cfg.seed, "ornaments")
    x0, y0, x1, y1 = _frame_box(lay)
    ppmm = cfg.px

    def lozenge(cx, cy, w, h, load=0.95, layer: Ink | None = None):
        p = diamond_path(cx, cy, w, h, rng, jitter=0.13)
        p = rotate_about(p, cx, cy, rng.uniform(-3.5, 3.5))
        cov = fill_path([to_px(p, cfg)], H, W)
        n = noise(rng, H, W, max(1.6, 0.6 * ppmm))
        (layer or red).stamp_field(cov * (0.80 + 0.20 * n), load * (0.62 + 0.38 * n))

    lw, lh = lay.lozenge_size_mm
    for cx in (x0, x1):
        cy = 0.5 * (lay.lozenge_y[0] + lay.lozenge_y[1]) * CARD_H_MM
        lozenge(cx, cy, lw, lh)
    dw, dh = lay.diamond_size_mm
    if lay.diamond_top_y is not None:
        lozenge(CARD_W_MM * 0.5, lay.diamond_top_y * CARD_H_MM, dw, dh)
    lozenge(CARD_W_MM * 0.5, lay.diamond_bottom_y * CARD_H_MM, dw, dh)
    cw, ch = lay.column_head_size_mm
    lozenge(CARD_W_MM * 0.5, lay.column_head_y * CARD_H_MM, cw, ch, load=0.90)

    # row 16: the black diamond ON the bottom rule - the bottom link of the vertical
    # chain down the centre of the card, which ours stopped short of
    if black is not None and lay.bottom_black_diamond is not None:
        bx, by = P(*lay.bottom_black_diamond)
        bw, bh = lay.bottom_black_diamond_mm
        lozenge(bx, by, bw, bh, load=1.0, layer=black)

    # row 17: the flanking leaf pair.  Measured on V1 as two small separate ink
    # components either side of the centre line at v ~ 130.7 mm.
    #
    # RE-MEASURED.  The second build laid them down BEFORE the lower-centre column, so
    # the black 瞬業 was painted straight over them: their POSITIONS passed the only
    # stated tolerance while 4 % and 28 % of the red survived and neither read as an
    # ornament at all.  V1 puts them inside the same column's x-span, so there is no
    # position inside the +-1.0 mm tolerance that clears the text.  What a card like this
    # actually is, is a sheet that was written and then STAMPED: the vermilion goes on
    # last and sits on top of the dry black.  So the coverage is returned here and
    # ``build_front`` knocks the black back out of it after the columns are set.
    leaf_cov = np.zeros((H, W), np.float32)
    for lx, ly, lw2, lh2 in lay.leaf_pair:
        cx, cy = P(lx, ly)
        p = diamond_path(cx, cy, lw2, lh2, rng, jitter=0.20)
        p = rotate_about(p, cx, cy, rng.uniform(-14.0, 14.0))
        cov = fill_path([to_px(p, cfg)], H, W)
        n = noise(rng, H, W, max(1.6, 0.6 * ppmm))
        cov = cov * (0.82 + 0.18 * n)
        red.stamp_field(cov, 0.90 * (0.66 + 0.34 * n))
        leaf_cov = np.maximum(leaf_cov, cov)

    # A tail ornament below the lower-centre column only if there is honestly room for
    # one.  With MasaFont's cells the column reaches 145 mm and the bottom rule is at
    # 148.6, so on this layout there is not: a 2 mm stub plus a second diamond a
    # millimetre above the bottom diamond is clutter, not ornament.  The gate stays so
    # a string swap that shortens the column gets its tail back.
    ty = lay.col_lower_centre_y[1] * CARD_H_MM + lay.col_lower_centre_cell_mm[1] * 0.72
    tail_end = lay.diamond_bottom_y * CARD_H_MM - 5.0
    if tail_end > ty + 6.0:
        p = np.stack([np.full(24, CARD_W_MM * 0.5), np.linspace(ty, tail_end, 24)], axis=1)
        p = wander(p, rng, 0.10, 6.0)
        t = np.linspace(0.0, 1.0, 32)
        wid = 1.05 * (1.0 - t) ** 1.25 + 0.10
        red.stamp(brush_stroke(p, wid, cfg=cfg, rng=rng, W=W, H=H, load=0.88,
                               dry=0.34, bristle_mm=0.22, streak_cell_mm=1.8,
                               edge_ragged=0.40, step_mm=0.30))
    return leaf_cov


def draw_ring(red: Ink, cfg: ArtConfig, lay: Layout, W: int, H: int) -> None:
    """One fast brush lap.  Not an annulus, not a circle, not concentric with the glyph.

    Study 5.2 / 5.5, and the study's own warning that this is the element most likely to
    be got wrong.  What has to be true: an ELLIPSE (h/w > 1) whose centre sits right of
    the card centre line; 5:1 weight variation along the lap; dry-brush streaks running
    ALONG the stroke over most of it with only two or three true gaps of a couple of
    degrees; a thick, wet start where the brush landed and a thin whip-out where it left.
    The lap overshoots its start by ~14 deg and rides slightly outside itself there, the
    way a real second-of-arc overlap does.
    """
    rng = _rng(cfg.seed, "ring")
    cx, cy = P(*lay.ring_centre)
    ow, oh = lay.ring_outer_mm
    wmin, wmax = lay.ring_stroke_mm

    a0 = math.radians(108.0)                       # land at the top, a little left
    a1 = a0 - math.radians(374.0)                  # clockwise, overshooting the start
    n = 620
    a = np.linspace(a0, a1, n)
    # the lap is not a clean ellipse: the radius breathes, as a fast arm does
    rr = noise(rng, 1, n, 150.0)[0] - 0.5
    rx = (ow * 0.5 - wmax * 0.55) * (1.0 + 0.062 * rr)
    ry = (oh * 0.5 - wmax * 0.55) * (1.0 + 0.062 * np.roll(rr, 137))
    # ride outside on the overlap
    over = _smoothstep((np.linspace(0, 1, n) - 0.955) / 0.045)
    rx = rx * (1.0 + 0.035 * over)
    ry = ry * (1.0 + 0.035 * over)
    path = np.stack([cx + rx * np.cos(a), cy - ry * np.sin(a)], axis=1)
    path = wander(path, rng, 0.60, 26.0)

    t = np.linspace(0.0, 1.0, 128)
    base = noise(rng, 1, 128, 13.0)[0]
    base = (base - base.min()) / max(float(np.ptp(base)), 1e-6)
    # REFERENCE_SPEC row 9 / worklist 9.  The swept band - the distance a radial ray
    # crosses from first ink to last - is 4.84 mm median on V1 with p05 1.48 and p95
    # 7.04.  Ours was 3.40 median, p95 4.96: a pen, not a loaded brush.  (Two other
    # "stroke width" definitions are in circulation at 6.15 and 5.31 mm.  They are all
    # defensible and they are NOT interchangeable - the build target and the acceptance
    # test both use the swept band, and nothing here mixes them.)
    shape = (0.02
             + 1.05 * np.exp(-((t - 0.040) / 0.080) ** 2)
             + 0.86 * np.exp(-((t - 0.300) / 0.075) ** 2)
             + 0.95 * np.exp(-((t - 0.560) / 0.110) ** 2)
             + 0.58 * np.exp(-((t - 0.735) / 0.070) ** 2))
    w = wmin + (wmax - wmin) * np.clip(0.78 * shape + 0.40 * base + 0.14, 0.0, 1.0)
    # worklist 24: TAPER THE LAST 40 DEGREES instead of thickening it.  40 deg of the
    # 374 deg lap is t > 0.893, and the taper is started a little before so the band
    # thins INTO its own gap rather than stopping at one.
    w *= 1.0 - 0.60 * _smoothstep((t - 0.820) / 0.180)
    w = np.maximum(w, wmin * 0.62)

    # ...and the INK LOAD ramps the same way.  Section 7: in the reference the band
    # thins into its own gap; ours ended WETTER than it started, which is why the ring
    # read directionless - you could not tell where the brush landed or where it ran
    # out.  The lap still has to stay PRESENT all the way round (angular coverage
    # 0.919, only two or three true gaps), so this is dryness, not absence.
    ld = np.clip(0.84 + 0.36 * np.exp(-(t / 0.13) ** 2) + 0.20 * base
                 - 0.56 * _smoothstep((t - 0.42) / 0.58), 0.30, 1.0)

    gaps = []
    span = 374.0
    for g0, g1 in lay.ring_gaps_deg:
        # measured as angles; the lap starts at 108 deg and runs clockwise
        f0 = ((108.0 - g1) % 360.0) / span
        f1 = ((108.0 - g0) % 360.0) / span
        gaps.append((f0, f1))

    # ONE lap, and the dryness lives in the ink's DENSITY, not in lanes cut between
    # full-opacity ribbons.  The first pass of this ring used bristle 0.26 mm with a
    # hard 0.085-wide threshold, which on a 4.7 mm stroke gives eighteen hairs and cuts
    # about half of them away: the result measured 3 separate radial ink runs at the
    # median angle and read, correctly, as three concentric vector circles.  Fat hairs
    # (0.62 mm), a long streak cell so the drags run several millimetres, most of the
    # dryness carried as density, and a wet spine are what make it one stroke.
    # REFERENCE_SPEC row 10 / worklist 11.  Section 6 is explicit that our kasure holes
    # are already the right SIZE (0.31 mm median against 0.30), the right SHAPE
    # (elongation 4.8 against 4.2) and the right ALIGNMENT (88 % within 30 deg of the
    # tangent against 83 %, where random would be 33 %).  Only the COUNT is short: 37
    # holes over 0.122 of the stroke envelope against the reference's 122 over 0.198.
    # So nothing about the hole geometry moves.  What moves is how often the bristle
    # field dips below the bare-paper level: a shorter streak cell makes each hair start
    # and stop more often at the same hole size, a higher dry raises the level, and less
    # dry_soft lets more of those dips reach bare paper instead of merely thinning.
    # Section 7's warning is the thing to watch by eye: the failure mode of "more holes"
    # is SPECKLE - voids scattered like film grain instead of clustered where a
    # splitting brush would leave them - which is what the streak field's along-stroke
    # correlation is for.
    # ...and with the band at the reference's own width the bristle field spans more
    # hairs, so the same dryness cuts a third more holes than it did at 3.4 mm: row 10's
    # hole fraction is 0.16 - 0.24 and a 9 mm band at dry 0.52 measured 0.286.  The
    # dryness comes down and the wet spine comes up; the hole SIZE, SHAPE and ALIGNMENT
    # that section 6 says are already right are set by the bristle and streak cells,
    # which do not move.
    red.stamp(brush_stroke(path, w, cfg=cfg, rng=rng, W=W, H=H, load=ld,
                           dry=0.47, bristle_mm=0.62, streak_cell_mm=2.05,
                           edge_ragged=0.34, gaps=gaps, step_mm=0.30,
                           dry_soft=0.60, core=0.54))

    # flecks thrown off where the brush landed and where it left
    for k in range(4):
        idx = int(rng.choice([6, 12, n - 26, n - 12]))
        p = path[idx]
        ang = rng.uniform(0, 2 * math.pi)
        ln = rng.uniform(0.9, 2.6)
        q = np.stack([np.linspace(p[0], p[0] + math.cos(ang) * ln, 10),
                      np.linspace(p[1], p[1] + math.sin(ang) * ln, 10)], axis=1)
        tt = np.linspace(0, 1, 12)
        red.stamp(brush_stroke(q, 0.42 * (1 - tt) ** 1.3 + 0.05, cfg=cfg, rng=rng,
                               W=W, H=H, load=0.55, dry=0.5, bristle_mm=0.20,
                               edge_ragged=0.5, step_mm=0.25))


