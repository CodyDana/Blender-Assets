def _edge_noise(rng, n: int, lobes: float) -> np.ndarray:
    """A smooth 0 - 1 ramp along an edge, ``lobes`` humps long."""
    k = max(2, int(lobes) + 2)
    ctrl = rng.random(k + 2).astype(np.float64)
    t = np.linspace(0.0, k - 1.0, n)
    i = np.clip(np.floor(t).astype(int), 0, k - 1)
    f = _smootherstep(t - i)
    return ctrl[i] * (1 - f) + ctrl[i + 1] * f


def card_outline_mm(cfg: ArtConfig, lay: Layout = LAYOUT) -> np.ndarray:
    """The trimmed outline as a closed polyline in card millimetres.

    The mesh and the texture must be cut to the SAME edge, so this is the one authority.
    Four 45 deg clips at 7.6 mm; a 16 mm torn stretch on the bottom edge with 6 - 12
    lobes deviating 0.5 - 1.5 mm; a 5 mm nick in the right edge at y 0.62.
    Deterministic in ``cfg.seed``.

    Every deviation goes INWARD, so the outline never leaves the 70.0 x 156.0 mm box
    the study builds to.  A hand-cut edge does wander both ways, but the fibres that
    hang past the trim are exactly what the study puts in T_PaperBomb_M's red channel
    rather than in geometry, and a card that measures 70.26 mm because of a decorative
    wobble is a mass gate and a UV layout quietly off by a quarter of a millimetre.
    """
    rng = _rng(cfg.seed, "outline")
    c = CORNER_CLIP_MM
    W, H = CARD_W_MM, CARD_H_MM

    def edge(p0, p1, n, amp, lobes, inward):
        p = np.linspace(0.0, 1.0, n)[:, None] * (np.array(p1) - np.array(p0)) + np.array(p0)
        off = _edge_noise(rng, n, lobes) * amp
        return p + np.asarray(inward, np.float64)[None, :] * off[:, None]

    top = edge((c, 0.0), (W - c, 0.0), 40, 0.20, 2.5, (0, 1))
    r_up = edge((W, c), (W, H * lay.nick_y - lay.nick_mm * 0.5), 40, 0.18, 4.0, (-1, 0))
    # the nick: a shallow V bitten out of the right edge
    nd = rng.uniform(0.8, 1.5)
    ny0 = H * lay.nick_y - lay.nick_mm * 0.5
    nick = np.array([
        [W, ny0],
        [W - nd * 0.55, ny0 + lay.nick_mm * 0.28],
        [W - nd, ny0 + lay.nick_mm * 0.52],
        [W - nd * 0.40, ny0 + lay.nick_mm * 0.78],
        [W, ny0 + lay.nick_mm],
    ])
    r_dn = edge((W, ny0 + lay.nick_mm), (W, H - c), 40, 0.18, 4.0, (-1, 0))

    # the torn stretch, placed off-centre on the bottom edge
    lobes = int(rng.integers(lay.tear_lobes[0], lay.tear_lobes[1] + 1))
    t0 = rng.uniform(0.18, 0.40) * (W - 2 * c) + c
    t1 = min(W - c - 1.0, t0 + lay.tear_stretch_mm)
    bl = edge((W - c, H), (t1, H), 30, 0.16, 2.0, (0, -1))
    xs = np.linspace(t1, t0, lobes * 5 + 1)
    phase = rng.random(lobes + 2)
    u = np.linspace(0.0, lobes * 1.0, len(xs))
    iu = np.clip(np.floor(u).astype(int), 0, lobes)
    f = _smootherstep(u - iu)
    amp = phase[iu] * (1 - f) + phase[iu + 1] * f
    lo, hi = lay.tear_deviation_mm
    dev = lo + (hi - lo) * amp
    # a tear takes material away, so every lobe bites inward, deeply or barely
    lobe_bite = 0.18 + 0.82 * rng.random(lobes + 2)
    bite = lobe_bite[iu] * (1 - f) + lobe_bite[iu + 1] * f
    fine = _edge_noise(rng, len(xs), lobes * 2.6) * 0.30
    torn = np.stack([xs, H - dev * bite - fine], axis=1)
    br = edge((t0, H), (c, H), 30, 0.16, 2.0, (0, -1))
    l_up = edge((0.0, H - c), (0.0, c), 60, 0.20, 5.0, (1, 0))

    return join(
        top,
        np.array([[W - c, 0.0], [W, c]]),
        r_up, nick, r_dn,
        np.array([[W, H - c], [W - c, H]]),
        bl, torn, br,
        np.array([[c, H], [0.0, H - c]]),
        l_up,
        np.array([[0.0, c], [c, 0.0]]),
    )


