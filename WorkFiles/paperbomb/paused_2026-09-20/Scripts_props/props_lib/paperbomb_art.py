def fill_path_win(polys: Sequence[np.ndarray], W: int, H: int, ss: int = 4):
    """Nonzero-winding fill of closed polylines given in PIXELS, over their own window.

    Rows are supersampled ``ss`` times and x coverage is exact to the fraction, which is
    how a font rasteriser does it; the result is clean at the 4 - 7 px features (the
    0.56 mm lozenge, the 0.42 mm inner rule) where a binary test would crawl.  Working
    in the polygon's own bounding box keeps a 14 mm glyph from paying for a 2048 raster.

    Returns ``(cov, x0, y0)`` or ``None``.
    """
    segs_a = []
    for p in polys:
        p = np.asarray(p, np.float64)
        if len(p) >= 3:
            segs_a.append(p)
    if not segs_a:
        return None
    a = np.concatenate(segs_a, axis=0)
    b = np.concatenate([np.roll(p, -1, axis=0) for p in segs_a], axis=0)

    bx0 = max(0, int(math.floor(a[:, 0].min())) - 1)
    bx1 = min(W, int(math.ceil(a[:, 0].max())) + 2)
    by0 = max(0, int(math.floor(a[:, 1].min())) - 1)
    by1 = min(H, int(math.ceil(a[:, 1].max())) + 2)
    if bx1 <= bx0 or by1 <= by0:
        return None
    ww, hh = bx1 - bx0, by1 - by0

    x0, y0 = a[:, 0] - bx0, a[:, 1] - by0
    x1, y1 = b[:, 0] - bx0, b[:, 1] - by0
    dy = y1 - y0
    keep = dy != 0.0
    if not np.any(keep):
        return None
    x0, y0, x1, y1, dy = x0[keep], y0[keep], x1[keep], y1[keep], dy[keep]
    direction = np.sign(dy)
    rows = hh * ss
    j0 = np.clip(np.ceil(np.minimum(y0, y1) * ss - 0.5).astype(np.int64), 0, rows)
    j1 = np.clip(np.ceil(np.maximum(y0, y1) * ss - 0.5).astype(np.int64), 0, rows)
    cnt = np.maximum(j1 - j0, 0)
    total = int(cnt.sum())
    if total == 0:
        return None

    si = np.repeat(np.arange(len(x0)), cnt)
    jj = np.repeat(j0, cnt) + (np.arange(total) - np.repeat(np.cumsum(cnt) - cnt, cnt))
    t = (((jj + 0.5) / ss) - y0[si]) / dy[si]
    xc = np.clip(x0[si] + t * (x1[si] - x0[si]), -1.0, ww + 1.0)
    ixf = np.floor(xc)
    fx = xc - ixf
    ix = ixf.astype(np.int64) + 1          # one guard column on the left
    cols = ww + 3
    d = direction[si]
    flat = jj * cols
    n = rows * cols
    acc = np.bincount(flat + np.clip(ix, 0, cols - 1), weights=d * (1.0 - fx), minlength=n)
    acc += np.bincount(flat + np.clip(ix + 1, 0, cols - 1), weights=d * fx, minlength=n)
    wind = np.cumsum(acc.reshape(rows, cols).astype(np.float32), axis=1)
    cov = np.clip(np.abs(wind[:, 1:ww + 1]), 0.0, 1.0)
    return cov.reshape(hh, ss, ww).mean(axis=1).astype(np.float32), bx0, by0


def fill_path(polys: Sequence[np.ndarray], H: int, W: int, ss: int = 4) -> np.ndarray:
    """``fill_path_win`` pasted into a full (H, W) raster."""
    out = np.zeros((H, W), np.float32)
    r = fill_path_win(polys, W, H, ss)
    if r is None:
        return out
    cov, x0, y0 = r
    out[y0:y0 + cov.shape[0], x0:x0 + cov.shape[1]] = cov
    return out


