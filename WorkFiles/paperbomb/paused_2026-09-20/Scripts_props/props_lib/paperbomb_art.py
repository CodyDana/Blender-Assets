def _edge_distance_mm(card: np.ndarray, ppmm: float, reach_mm: float) -> np.ndarray:
    """A 0 - 1 ramp inward from the trimmed edge, reaching ~``reach_mm`` inside.

    A blur of the card mask is enough: the edge band only has to be right over the first
    couple of millimetres (the study's band falls to its dark value at 1 mm) and a true
    EDT would cost more than it is worth.
    """
    sig = max(0.7, reach_mm * ppmm * 0.36)
    return np.clip(blur(card, sig), 0.0, 1.0)


def paper_ground(cfg: ArtConfig, lay: Layout, W: int, H: int, card: np.ndarray,
                 side: str = "front", sheet_seed: int | None = None) -> dict:
    """The aged sheet: fibre, blotching, edge darkening, thumbing, foxing, a stain or two.

    Worn, thumbed, slightly grubby at the edges - the pack's philosophy applied to paper
    instead of steel.  Nothing here is clean noise: every field is at a real millimetre
    cell size out of the study's table, and the grime is placed where a thumb goes.
    """
    ppmm = cfg.px
    rng = _rng(cfg.seed, "paper_" + side)
    sheet_seed = cfg.seed if sheet_seed is None else sheet_seed
    pal = palette_for(cfg)
    floor_lin, ceil_lin = ink_floor(cfg)

    base = np.array(pal.paper, np.float32)
    edge_col = np.array(pal.paper_edge, np.float32)

    # --- value fields.
    #
    # REFERENCE_SPEC rows 25 and 26, and section 7's "how much wear is right": BOTH
    # guides are clean, evenly aged sheets, and ours was a used prop.  This targets the
    # guides.  Two measured facts drive the sizes:
    #
    #   row 26  mottle - our AMPLITUDE is right (2.48 % against 2.02 %) and our SCALE is
    #           not: the power sits in the 3 - 10 mm band where the reference's sits in
    #           1 - 3 mm, so we get a soft gradient where the reference has foxing.
    #   row 25  grain  - 17.0 % amplitude on a 0.50 mm cell at anisotropy 1.90, against
    #           our 9.8 % on a 2.79 mm cell at anisotropy 17.2.  V1 ONLY: every V2
    #           fine-texture figure sits past its own Nyquist limit.
    mottle = fbm(rng, H, W, 26.0 * ppmm, octaves=3) - 0.5           # 15 - 40 mm cells
    # the 3 - 10 mm band comes down and the 1 - 3 mm band comes up (row 26).  Both stay
    # SMALL: the reference's whole mottle amplitude is 2.02 % against a 17 % grain, so
    # the sheet's character is its fibre and not its blotching.
    blotch = fbm(rng, H, W, 6.5 * ppmm, octaves=2) - 0.5
    close = fbm(rng, H, W, 1.9 * ppmm, octaves=2) - 0.5
    # the laid fibre itself: a 0.50 mm cell at 1.9:1, which is what "grain" measures
    # the fibres lie along the sheet's LONG axis, so the anisotropy runs in y: aniso < 1
    # stretches the cells vertically.  The spec measures anisotropy 1.90 without a
    # direction, and a laid sheet's fibres follow the mould, which on a 70 x 156 card is
    # the long way.  It also makes the card's row statistics honest - horizontal fibres
    # correlate along a row and leave a crease test measuring its own grain.
    #
    # THIRD BUILD - ROW 26 IS CALIBRATED AGAINST THE SHEET, NOT AGAINST ITS OWN NUMBER.
    # The row's stated 17.0 % amplitude on a 0.50 mm cell is not reproducible: run the
    # SAME instrument over V1 and it reads 3.63 % on a 1.59 mm cell (see
    # ``WorkFiles/paperbomb/grain_calibration.py`` and its json, and an independent
    # fourth pass got 2.69 % / 1.19 - 1.40 mm on its own instrument).  Built to the
    # stated figure, ours came out at 14.33 % on a 0.62 mm cell - 3.95x the reference
    # sheet's grain at 39 % of its correlation length, confirmed by texture energy at
    # the same 3.95x - and the trajectory across three builds ran AWAY from the guide.
    # So the target is the guide measured like for like: amplitude / 3.95, correlation
    # length x 2.6.  ``GRAIN_LIKE_FOR_LIKE`` records the calibration the build is aimed
    # at and ``art_metrics.grain`` gates it.
    grain = fbm(rng, H, W, max(1.5, 1.22 * ppmm), octaves=2, aniso=1.0 / 1.12) - 0.5
    micro = noise(rng, H, W, max(1.5, 0.58 * ppmm)) - 0.5

    v = (1.0 + mottle * 0.055
         + blotch * 0.030
         + close * 0.034
         + grain * 0.181
         + micro * 0.044)

    # --- long kozo fibres: a few visible threads, 10 - 15 mm, lying flat
    fib = np.zeros((H, W), np.float32)
    nf = int(26 * cfg.wear)
    for _ in range(nf):
        x = rng.uniform(0, CARD_W_MM); y = rng.uniform(0, CARD_H_MM)
        ang = rng.uniform(0, math.pi)
        L = rng.uniform(9.0, 15.0)
        p = np.stack([np.linspace(x, x + math.cos(ang) * L, 16),
                      np.linspace(y, y + math.sin(ang) * L, 16)], axis=1)
        p = wander(p, rng, 0.35, 5.0)
        win = brush_stroke(p, rng.uniform(0.07, 0.16), cfg=cfg, rng=rng, W=W, H=H,
                           load=1.0, dry=0.45, bristle_mm=0.05, edge_ragged=0.6,
                           step_mm=0.4, aa=1.4)
        if win is not None:
            h_, w_ = win.shape
            sl = (slice(win.y0, win.y0 + h_), slice(win.x0, win.x0 + w_))
            # the sign has to be applied to the STAMP, not inside a max against zero -
            # written the old way every dark fibre was silently thrown away
            amp = rng.uniform(-1.0, 1.0)
            if amp >= 0.0:
                fib[sl] = np.maximum(fib[sl], win.cov * amp)
            else:
                fib[sl] = np.minimum(fib[sl], win.cov * amp)
    v = v + fib * 0.055

    rgb = base[None, None, :] * v[:, :, None]

    # --- edge darkening.
    #
    # REFERENCE_SPEC row 25 / worklist 23.  The guides' band is 15 % deep, 95 % recovered
    # by 7.25 mm, the four sides agree within 1.5 points and the tilt across the card is
    # under 0.8 %.  Ours was 21.9 % deep with a reach of 14.75 mm, the four sides 12.4
    # points apart and a 5.3 % tilt - a vignette that ate a fifth of the card width and
    # had a DIRECTION, which reads as a bug rather than as wear.
    #
    # So: ONE isotropic profile driven by one distance ramp, at the measured depth, with
    # only a light break-up (+-9 %) so the four sides cannot disagree, and no corner
    # boost at all - the reference has no thumb, it has an evenly aged sheet.
    # _edge_distance_mm is a blur of the card mask, which reads 0.5 ON the trim line and
    # ~0.95 about half a reach inside, so a reach of 14.0 puts the 95 % recovery at
    # about 7.2 mm.
    # row 25's reach clause: 95 % recovered by 7.25 mm, tolerance 6 - 9.  Measured in
    # LINEAR luma (which is the reference's own space) a shallower band recovers sooner,
    # and at a 14.0 reach this read 5.8 mm - under the floor - where in stored sRGB it
    # had read 7.3.  The profile is the same shape; only the yardstick changed.
    ramp = _edge_distance_mm(card, ppmm, 16.0)
    tight = _edge_distance_mm(card, ppmm, 2.4)
    broken = 0.91 + 0.18 * fbm(rng, H, W, 11.0 * ppmm, octaves=2)
    eband = np.clip((1.00 * (1.0 - _smoothstep((ramp - 0.50) / 0.44))
                     + 0.26 * (1.0 - _smoothstep((tight - 0.50) / 0.46))) * broken,
                    0.0, 1.0) * cfg.wear
    rgb = rgb * (1.0 - eband[:, :, None]) + edge_col[None, None, :] * eband[:, :, None]

    yy, xx = mm_grid(cfg, H, W)

    # --- thumbing.  The reference sheets are handled but not grubby, so this is now one
    # very soft, very shallow patch per bottom corner rather than the two hard lobes plus
    # a pinch mark the first build drew.
    grime = np.zeros((H, W), np.float32)
    for gx, gy, r in ((rng.uniform(7, 13), CARD_H_MM - rng.uniform(7, 13), 13.0),
                      (CARD_W_MM - rng.uniform(7, 13), CARD_H_MM - rng.uniform(7, 13), 13.0)):
        d = np.hypot(xx - gx, yy - gy) / r
        grime = np.maximum(grime, np.clip(1.0 - d, 0.0, 1.0) ** 2.0)
    grime *= (0.45 + 0.85 * fbm(rng, H, W, 8.0 * ppmm, octaves=3)) * cfg.wear
    grime = np.clip(grime, 0.0, 1.0)
    rgb = rgb * (1.0 - grime[:, :, None] * (1.0 - pal.thumb_factor))

    # --- stains and foxing.
    #
    # THE SQUARE-PATCH DEFECT.  A field that is built from a noise WINDOW rather than
    # from a whole-card field shows its window as an axis-aligned rectangle the moment
    # anything downstream raises its contrast, and a hard rectangle in a paper texture is
    # the most synthetic mark a prop can carry.  Everything here is therefore built from
    # whole-card fields and multiplied by a RADIAL falloff that is zero well before any
    # window edge could exist, the boundary is warped by two octaves of domain noise so
    # it is never straight, and ``art_metrics.hard_rect_discontinuity`` scans the finished
    # base colour for any straight run of high gradient and FAILS the build if it finds
    # one.  (The eight square patches the reviews caught in the shipped render were not
    # from here at all - they were the AO bake reading eight front/back face
    # self-intersections in the LOD0 shell; see props_lib.sheet.skin_pair.)
    stain_f = np.zeros((H, W), np.float32)
    warp_a = (fbm(rng, H, W, 11.0 * ppmm, octaves=3) - 0.5)
    warp_b = (fbm(rng, H, W, 3.6 * ppmm, octaves=3) - 0.5)
    for _ in range(2):
        sx = rng.uniform(14, CARD_W_MM - 14)
        sy = rng.uniform(20, CARD_H_MM - 20)
        r = rng.uniform(6.0, 9.5)
        # the boundary wanders by up to 60 % of the radius at two scales: an organic,
        # soft, irregular edge that can never be mistaken for a tile
        d = (np.hypot(xx - sx, yy - sy) + warp_a * r * 0.46 + warp_b * r * 0.19) / r
        body = _smoothstep((1.02 - d) / 0.55) ** 0.9
        tide = np.exp(-((d - 0.92) / 0.20) ** 2)
        stain_f = np.maximum(stain_f, body * 0.30 + tide * 0.34)
    stain_f = np.clip(stain_f, 0.0, 1.0) * 0.055 * cfg.wear
    rgb = rgb * (1.0 - stain_f[:, :, None]) + np.array(pal.stain, np.float32)[None, None, :] * stain_f[:, :, None]

    # foxing: discrete oxidation spots, never clustered, each one a warped disc
    fox = np.zeros((H, W), np.float32)
    nspots = int(rng.integers(4, 11))
    placed: list[tuple[float, float]] = []
    tries = 0
    while len(placed) < nspots and tries < 200:
        tries += 1
        sx = rng.uniform(4, CARD_W_MM - 4)
        sy = rng.uniform(4, CARD_H_MM - 4)
        if any(math.hypot(sx - a, sy - b) < 9.0 for a, b in placed):
            continue
        placed.append((sx, sy))
        r = rng.uniform(0.24, 0.80)
        d = (np.hypot(xx - sx, yy - sy) + warp_b * r * 0.55) / r
        fox = np.maximum(fox, _smoothstep((1.0 - d) / 0.7) ** 0.8)
    fox = fox * (0.55 + 0.65 * noise(rng, H, W, 1.2 * ppmm)) * cfg.wear
    fox = np.clip(fox, 0.0, 1.0) * 0.46
    rgb = rgb * (1.0 - fox[:, :, None]) + np.array(pal.foxing, np.float32)[None, None, :] * fox[:, :, None]

    # --- creases.
    #
    # REFERENCE_SPEC row 24 / worklist 22: NEITHER guide has any fold, crease or internal
    # shadow at all, and our base colour carried two row-luma lines at 51.6 and 104.4 mm.
    # ``FoldSpec`` puts a real 7 deg crease over a 2.2 mm half width into the GEOMETRY and
    # the lighting shades it; baking it into the albedo as well shades it twice and reads
    # as printed-on dirt.  The fields are still computed - the relief and the show-through
    # want to know where the folds are - but nothing multiplies them into ``rgb``.
    crease = np.zeros((H, W), np.float32)
    crease_signed = np.zeros((H, W), np.float32)
    for k, cy_f in enumerate(lay.crease_y):
        cy = cy_f * CARD_H_MM
        # the same sheet, so the same creases: keyed to the card seed, mirrored on the back
        wob = (noise(_rng(sheet_seed, "crease%d" % k), 1, W, 9.0 * ppmm)[0] - 0.5) * 2.0 * lay.crease_wander_mm
        if side == "back":
            wob = wob[::-1]
        line = cy + wob
        d = (yy - line[None, :])
        g = np.exp(-(d / 0.55) ** 2)
        crease = np.maximum(crease, g)
        crease_signed += g * np.sign(0.5 - ((d < 0).astype(np.float32)))
        crease_signed += -np.exp(-((d - 0.85) / 0.75) ** 2) * 0.45
    dg = lay.dogear_corner_mm
    diag = (CARD_W_MM - xx) + (CARD_H_MM - yy)
    dog = _smoothstep((dg - diag) / 1.1)
    crease = np.maximum(crease, np.exp(-((diag - dg) / 0.7) ** 2))

    rough = np.full((H, W), pal.rough_paper, np.float32)
    rough += (pal.rough_paper_edge - pal.rough_paper) * eband
    rough += 0.04 * grime + 0.02 * fox
    rough += 0.03 * (grain + micro)

    return {
        "rgb": np.clip(rgb, floor_lin, ceil_lin).astype(np.float32),
        "rough": np.clip(rough, 0.30, 0.98).astype(np.float32),
        "grain": (grain + micro * 0.6).astype(np.float32),
        "fibre": fib.astype(np.float32),
        "crease": crease.astype(np.float32),
        "crease_signed": crease_signed.astype(np.float32),
        "dogear": dog.astype(np.float32),
        "edge_band": eband.astype(np.float32),
        "grime": grime.astype(np.float32),
        "foxing": fox.astype(np.float32),
        "stain": stain_f.astype(np.float32),
    }


