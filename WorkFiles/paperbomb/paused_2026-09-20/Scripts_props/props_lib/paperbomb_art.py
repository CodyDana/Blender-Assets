def bezier(p0, p1, p2, p3, n: int = 48) -> np.ndarray:
    t = np.linspace(0.0, 1.0, n)[:, None]
    mt = 1.0 - t
    p0 = np.asarray(p0, np.float64); p1 = np.asarray(p1, np.float64)
    p2 = np.asarray(p2, np.float64); p3 = np.asarray(p3, np.float64)
    return (mt ** 3) * p0 + 3 * (mt ** 2) * t * p1 + 3 * mt * (t ** 2) * p2 + (t ** 3) * p3


def join(*parts: np.ndarray) -> np.ndarray:
    out = [np.asarray(parts[0], np.float64)]
    for p in parts[1:]:
        p = np.asarray(p, np.float64)
        if np.allclose(out[-1][-1], p[0], atol=1e-9):
            p = p[1:]
        out.append(p)
    return np.concatenate(out, axis=0)


def arclen(p: np.ndarray) -> np.ndarray:
    d = np.diff(p, axis=0)
    s = np.concatenate([[0.0], np.cumsum(np.hypot(d[:, 0], d[:, 1]))])
    return s


def resample(p: np.ndarray, step: float) -> tuple[np.ndarray, np.ndarray]:
    """Even resampling by arclength.  Returns (points, arclength-at-point)."""
    p = np.asarray(p, np.float64)
    s = arclen(p)
    total = float(s[-1])
    if total <= 1e-9:
        return p[:1], np.zeros(1)
    n = max(2, int(math.ceil(total / step)) + 1)
    ss = np.linspace(0.0, total, n)
    x = np.interp(ss, s, p[:, 0])
    y = np.interp(ss, s, p[:, 1])
    return np.stack([x, y], axis=1), ss


def wander(p: np.ndarray, rng, amp: float, cell: float) -> np.ndarray:
    """Push a path sideways by a smooth noise - the reason no rule here is ruled."""
    p = np.asarray(p, np.float64)
    if len(p) < 3 or amp <= 0.0:
        return p
    d = np.gradient(p, axis=0)
    n = np.stack([-d[:, 1], d[:, 0]], axis=1)
    ln = np.hypot(n[:, 0], n[:, 1])
    ln[ln < 1e-12] = 1.0
    n /= ln[:, None]
    s = arclen(p)
    k = max(2, int(s[-1] / max(cell, 1e-6)) + 2)
    ctrl = rng.random(k + 3) - 0.5
    t = np.linspace(0.0, k - 1.0, len(p))
    idx = np.clip(np.floor(t).astype(int), 0, k - 1)
    f = _smootherstep(t - idx)
    off = ctrl[idx] * (1 - f) + ctrl[idx + 1] * f
    return p + n * (off * 2.0 * amp)[:, None]


def spiral_path(cx: float, cy: float, r0: float, r1: float,
                turns: float, a0: float = 0.0, n: int = 260) -> np.ndarray:
    a = np.linspace(a0, a0 + turns * 2.0 * math.pi, n)
    r = np.linspace(r0, r1, n)
    return np.stack([cx + r * np.cos(a), cy - r * np.sin(a)], axis=1)


def rotate_about(pts: np.ndarray, cx: float, cy: float, deg: float,
                 dx: float = 0.0, dy: float = 0.0) -> np.ndarray:
    """Used on the seal boxes: a stamp is never square to a printed frame."""
    a = math.radians(deg)
    c, s = math.cos(a), math.sin(a)
    p = np.asarray(pts, np.float64) - np.array([cx, cy])
    r = np.stack([p[:, 0] * c - p[:, 1] * s, p[:, 0] * s + p[:, 1] * c], axis=1)
    return r + np.array([cx + dx, cy + dy])


def rect_path(x0: float, y0: float, x1: float, y1: float) -> np.ndarray:
    return np.array([[x0, y0], [x1, y0], [x1, y1], [x0, y1]], np.float64)


def diamond_path(cx: float, cy: float, w: float, h: float, rng=None,
                 jitter: float = 0.10) -> np.ndarray:
    """A lozenge.  The four points are nudged so it is a stamped mark, not a vector kite."""
    pts = np.array([[cx, cy - h * 0.5], [cx + w * 0.5, cy],
                    [cx, cy + h * 0.5], [cx - w * 0.5, cy]], np.float64)
    if rng is not None and jitter > 0.0:
        pts += (rng.random((4, 2)) - 0.5) * np.array([w, h]) * jitter
    mid = 0.5 * (pts + np.roll(pts, -1, axis=0))
    out = np.empty((8, 2), np.float64)
    out[0::2] = pts
    out[1::2] = mid
    return out


