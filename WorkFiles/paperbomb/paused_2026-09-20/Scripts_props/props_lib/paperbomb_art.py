def draw_seals(red: Ink, cfg: ArtConfig, lay: Layout, W: int, H: int) -> dict:
    """Two stamps that behave differently, which is what sells them as stamps.

    LEFT, the big one: a solid vermilion panel inside a ruled frame, with the flame
    device KNOCKED OUT in paper colour - a carved seal prints the stone, not the mark.
    RIGHT, the small one: an open frame with red characters inside, a shop chop.
    Both are rotated 0.6 - 1.2 deg off the printed frame and offset 0.2 - 0.4 mm, and
    both have crisper edges than the brushwork, broken by ink starvation over 5 - 15 %
    of their length.
    """
    rng = _rng(cfg.seed, "seals")
    ppmm = cfg.px
    info = {}

    def stamped_frame(x0, y0, x1, y1, weight, rot, dx, dy, dry=0.30, load=0.94):
        """One chop's ruled frame, CONFINED to its own box.

        REFERENCE_SPEC rows 19 and 20: both frame boxes are right in the layout and
        wrong on the paper.  The big seal drew 20.12 x 29.71 where the guide measures
        18.0 x 26.5, and the small one 10.7 x 21.9 against 9.0 x 17.8 - the wander, the
        corner extension and the ragged edge between them walked the ink one to two
        millimetres past the frame on every side.  A carved chop cannot print outside
        its own stone, so the ink is clipped to the box plus half a rule plus
        ``seal_frame_bleed_mm``, and the clip is what the box measurement now sees.
        """
        cxm, cym = 0.5 * (x0 + x1), 0.5 * (y0 + y1)
        # THE RULE IS DRAWN INSIDE THE FRAME, not centred on it.  A chop's box is the
        # outside of its stone, and REFERENCE_SPEC rows 19 and 20 measure exactly that -
        # 9.0 x 17.8 mm on the small one, 18.0 x 26.5 on the big.  Section 6 confirms
        # our frame RECTANGLES already sit within 0.4 mm of the guide's, so putting the
        # rule's centre line on them drew every box a full rule too big in both axes,
        # and that alone was most of the "+21 %" row 19 reports.  Inset by half a rule
        # the drawn box and the specified frame are the same number.
        h = weight * 0.5
        x0, y0, x1, y1 = x0 + h, y0 + h, x1 - h, y1 - h
        corners = [(x0, y0), (x1, y0), (x1, y1), (x0, y1), (x0, y0)]
        ext = weight * 0.5          # run each side past its corner so the box closes
        pad = weight * 0.5 + lay.seal_frame_bleed_mm
        yy, xx = mm_grid(cfg, H, W)
        # the box, in the stamp's own rotated frame
        ca, sa = math.cos(math.radians(-rot)), math.sin(math.radians(-rot))
        ux = (xx - (cxm + dx)) * ca - (yy - (cym + dy)) * sa
        uy = (xx - (cxm + dx)) * sa + (yy - (cym + dy)) * ca
        # the clip is the SPECIFIED frame plus the bleed, not the inset centre line
        half_w = 0.5 * (x1 - x0) + h + lay.seal_frame_bleed_mm
        half_h = 0.5 * (y1 - y0) + h + lay.seal_frame_bleed_mm
        keep = ((np.abs(ux) <= half_w) & (np.abs(uy) <= half_h)).astype(np.float32)
        acc = np.zeros((H, W), np.float32)
        aload = np.zeros((H, W), np.float32)
        for i in range(4):
            p0 = np.array(corners[i], np.float64); p1 = np.array(corners[i + 1], np.float64)
            d = p1 - p0
            d /= max(float(np.hypot(*d)), 1e-9)
            p0 = p0 - d * ext
            p1 = p1 + d * ext
            p = np.linspace(0.0, 1.0, 60)[:, None] * (p1 - p0) + p0
            p = rotate_about(p, cxm, cym, rot, dx, dy)
            p = wander(p, rng, 0.010, 9.0)
            wid = weight * (0.90 + 0.20 * noise(rng, 1, 40, 6.0)[0])
            # a chop's frame is CRISPER than the brushwork round it - dry_soft stays
            # low so the starvation reads as the stone failing to take, not as a
            # thinning brush - but it is genuinely broken over part of its run
            win = brush_stroke(p, wid, cfg=cfg, rng=rng, W=W, H=H,
                               load=load, dry=dry, bristle_mm=0.22,
                               streak_cell_mm=1.5, edge_ragged=0.22, step_mm=0.26,
                               aa=0.65, dry_soft=0.25, core=0.25)
            if win is None:
                continue
            h_, w_ = win.shape
            sl = (slice(win.y0, win.y0 + h_), slice(win.x0, win.x0 + w_))
            m = win.cov > acc[sl]
            aload[sl] = np.where(m, win.load, aload[sl])
            acc[sl] = np.maximum(acc[sl], win.cov)
        red.stamp_field(acc * keep, aload)

    # ---- big seal --------------------------------------------------------
    fx0, fy0 = P(lay.big_seal_frame_x[0], lay.big_seal_frame_y[0])
    fx1, fy1 = P(lay.big_seal_frame_x[1], lay.big_seal_frame_y[1])
    rot = rng.uniform(0.6, 1.2) * rng.choice([-1.0, 1.0])
    dx, dy = rng.uniform(-0.4, 0.4), rng.uniform(-0.4, 0.4)
    stamped_frame(fx0, fy0, fx1, fy1, lay.big_seal_rule_mm, rot, dx, dy)

    px0, py0 = P(lay.big_seal_panel_x[0], lay.big_seal_panel_y[0])
    px1, py1 = P(lay.big_seal_panel_x[1], lay.big_seal_panel_y[1])
    pcx, pcy = 0.5 * (px0 + px1), 0.5 * (py0 + py1)
    panel = wander(resample(rect_path(px0, py0, px1, py1), 0.5)[0], rng, 0.045, 5.0)
    panel = rotate_about(panel, 0.5 * (fx0 + fx1), 0.5 * (fy0 + fy1), rot, dx, dy)
    pcov = fill_path([to_px(panel, cfg)], H, W)
    # A STAMP FIELD, not a fill.  The first pass varied coverage over 0.94 - 1.00 and
    # load over 0.88 - 1.00, which measured a red-channel sigma of 1.4/255 inside the
    # panel: dead flat, razor-edged, a vector rectangle pasted on the paper.  A carved
    # seal pressed in shuniku is uneven at two scales, has a few places where the stone
    # did not take at all, and is bitten into along part of its edge (study 5.5).
    sg = _rng(cfg.seed, "seal_grain")
    coarse = fbm(sg, H, W, max(3.0, 3.2 * ppmm), octaves=3)          # 2 - 5 mm cells
    fine = fbm(sg, H, W, max(2.0, 0.55 * ppmm), octaves=3)           # the paper's tooth
    take = np.clip(0.46 + 0.62 * coarse + 0.22 * (fine - 0.5), 0.0, 1.0)
    # a handful of starvation voids
    void = _smoothstep((fbm(sg, H, W, max(2.4, 1.3 * ppmm), octaves=3) - 0.800) / 0.060)
    # the edge is crisp but bitten over part of its run
    rim = np.clip((0.88 - blur(pcov, 0.85 * ppmm)) / 0.52, 0.0, 1.0) * pcov
    bite = _smoothstep((fbm(sg, H, W, max(2.4, 1.8 * ppmm), octaves=2) - 0.560) / 0.150)
    alpha = pcov * (0.92 + 0.08 * take) * (1.0 - 0.38 * void) * (1.0 - 0.52 * rim * bite)
    red.stamp_field(alpha, np.clip(0.72 + 0.28 * take, 0.0, 1.0))

    fr = _rng(cfg.seed, "seal_flame")
    # The device is knocked out in paper colour, and the spiral CUT inside it stays
    # vermilion - inside a carved relief the uncut stone still prints.  That is why the
    # seal's swirl reads red-on-white while the emblem's reads white-on-black.
    fcov, _fl, _fcut = flame_device(cfg, fr, W, H, pcx + dx, pcy + dy,
                                    (px1 - px0) * 0.66, (py1 - py0) * 0.685,
                                    style="seal", rotate_deg=rot, lay=lay)
    red.knock_out(fcov * pcov, 0.97)
    info["big_seal_rot_deg"] = round(float(rot), 3)

    # ---- small seal ------------------------------------------------------
    sx0, sy0 = P(lay.small_seal_frame_x[0], lay.small_seal_frame_y[0])
    sx1, sy1 = P(lay.small_seal_frame_x[1], lay.small_seal_frame_y[1])
    srot = rng.uniform(0.6, 1.2) * rng.choice([-1.0, 1.0])
    sdx, sdy = rng.uniform(-0.35, 0.35), rng.uniform(-0.35, 0.35)
    stamped_frame(sx0, sy0, sx1, sy1, lay.small_seal_rule_mm, srot, sdx, sdy, dry=0.38)
    info["small_seal_rot_deg"] = round(float(srot), 3)
    info["small_seal_transform"] = (float(srot), float(sdx), float(sdy),
                                    float(0.5 * (sx0 + sx1)), float(0.5 * (sy0 + sy1)))
    return info


