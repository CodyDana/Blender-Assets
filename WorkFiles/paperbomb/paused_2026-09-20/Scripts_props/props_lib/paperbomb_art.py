class Ink:
    """One colour of ink on the sheet: opacity ``a`` and load ``d``."""

    def __init__(self, H: int, W: int):
        self.a = np.zeros((H, W), np.float32)
        self.d = np.zeros((H, W), np.float32)
        #: where ink must never come back.  A knocked-out device is bare paper by
        #: construction - the stone was carved away - so the bleed is not allowed to
        #: wick back into it and turn a crisp spiral into a grey smudge.
        self.keep = np.zeros((H, W), np.float32)

    def stamp(self, win: Window | None) -> None:
        if win is None:
            return
        h, w = win.shape
        sl = (slice(win.y0, win.y0 + h), slice(win.x0, win.x0 + w))
        a = self.a[sl]
        m = win.cov > a
        self.d[sl] = np.where(m, win.load, self.d[sl])
        self.a[sl] = np.maximum(a, win.cov)

    def stamp_field(self, cov: np.ndarray, load) -> None:
        if np.isscalar(load):
            load = np.full_like(cov, float(load))
        m = cov > self.a
        self.d = np.where(m, load, self.d).astype(np.float32)
        self.a = np.maximum(self.a, cov).astype(np.float32)

    def knock_out(self, cov: np.ndarray, amount: float = 1.0) -> None:
        """Take ink away - how a carved seal prints its device in paper colour."""
        k = (amount * np.clip(cov, 0.0, 1.0)).astype(np.float32)
        self.a = (self.a * (1.0 - k)).astype(np.float32)
        self.keep = np.maximum(self.keep, k)

    def protect(self, cov: np.ndarray) -> None:
        """Mark a region as deliberately bare, without removing anything now."""
        self.keep = np.maximum(self.keep, np.clip(cov, 0.0, 1.0)).astype(np.float32)


def ink_bleed(layer: Ink, ppmm: float, rng, mm: float = 0.28,
              strength: float = 0.30) -> None:
    """Wick a soft ragged halo into the fibre.

    Study 5.5: heavy strokes wick 0.15 - 0.4 mm with a soft, slightly ragged boundary,
    stronger across the fibre than along it; thin fast strokes barely bleed.  "Heavy"
    is read off the stroke itself - a blur of the opacity is a cheap proxy for how much
    ink is sitting in one place.
    """
    if strength <= 0.0:
        return
    sig = max(0.6, mm * ppmm)
    soft = blur_aniso(layer.a, sig * 0.75, sig * 1.25)
    heavy = _smoothstep((blur(layer.a, sig * 3.0) - 0.16) / 0.42)
    H, W = layer.a.shape
    rag = noise(rng, H, W, max(1.8, 0.45 * ppmm))
    halo = (np.clip(soft - layer.a, 0.0, 1.0) * heavy * strength * (0.45 + 1.1 * rag)
            * (1.0 - layer.keep))
    # Ink only wicks OUT of a mark.  Inside a solid one the blur is a hair above the
    # local value simply because the coverage is not perfectly flat, and treating that
    # as bleed used to drag the load down to the dry colour in patches - which reads as
    # olive camouflage across the middle of the flame emblem.
    halo = np.where(layer.a > 0.88, 0.0, halo)
    # and the dryness is proportional to HOW MUCH of the pixel is wicked ink, not a
    # switch thrown by any halo at all
    w = np.clip(halo / 0.10, 0.0, 1.0)
    layer.d = (layer.d * (1.0 - w)
               + np.minimum(layer.d, 0.26 + 0.30 * layer.d) * w).astype(np.float32)
    layer.a = np.clip(layer.a + halo, 0.0, 1.0).astype(np.float32)


