@dataclass
class Window:
    """A float field and where it sits in the full raster."""
    x0: int
    y0: int
    cov: np.ndarray
    load: np.ndarray

    @property
    def shape(self):
        return self.cov.shape


def _stroke_fields(pts_px: np.ndarray, half_px: np.ndarray, W: int, H: int,
                   aa: float = 0.85):
    """Sweep a variable-width brush and return (cov, s, u, x0, y0) over its own window.

    ``s`` is arclength in pixels and ``u`` is the signed offset across the stroke divided
    by the local half width, so u = +-1 is the edge.  Everything else the brush does -
    dry streaks, load falloff, ragged edges - is a function of (s, u), which is what
    keeps the streaks running along the stroke instead of across it.
    """
    n = len(pts_px)
    if n < 2:
        return None
    s_at = arclen(pts_px)
    max_half = float(half_px.max())
    pad = max_half + aa + 2.0
    bx0 = int(math.floor(pts_px[:, 0].min() - pad))
    bx1 = int(math.ceil(pts_px[:, 0].max() + pad))
    by0 = int(math.floor(pts_px[:, 1].min() - pad))
    by1 = int(math.ceil(pts_px[:, 1].max() + pad))
    bx0 = max(bx0, 0); by0 = max(by0, 0)
    bx1 = min(bx1, W); by1 = min(by1, H)
    if bx1 <= bx0 or by1 <= by0:
        return None
    ww, hh = bx1 - bx0, by1 - by0
    cov = np.zeros((hh, ww), np.float32)
    sf = np.zeros((hh, ww), np.float32)
    uf = np.zeros((hh, ww), np.float32)
    vf = np.zeros((hh, ww), np.float32)      # signed offset across the stroke, in PIXELS

    for i in range(n - 1):
        ax, ay = pts_px[i]
        bxp, byp = pts_px[i + 1]
        ha, hb = float(half_px[i]), float(half_px[i + 1])
        hmax = max(ha, hb)
        sx0 = max(bx0, int(math.floor(min(ax, bxp) - hmax - aa - 1)))
        sx1 = min(bx1, int(math.ceil(max(ax, bxp) + hmax + aa + 1)))
        sy0 = max(by0, int(math.floor(min(ay, byp) - hmax - aa - 1)))
        sy1 = min(by1, int(math.ceil(max(ay, byp) + hmax + aa + 1)))
        if sx1 <= sx0 or sy1 <= sy0:
            continue
        gx = np.arange(sx0, sx1, dtype=np.float32) + 0.5
        gy = np.arange(sy0, sy1, dtype=np.float32) + 0.5
        qx = gx[None, :] - np.float32(ax)
        qy = gy[:, None] - np.float32(ay)
        dx = np.float32(bxp - ax)
        dy = np.float32(byp - ay)
        dd = float(dx * dx + dy * dy)
        if dd < 1e-12:
            t = np.zeros((sy1 - sy0, sx1 - sx0), np.float32)
        else:
            t = np.clip((qx * dx + qy * dy) / dd, 0.0, 1.0)
        px = qx - t * dx
        py = qy - t * dy
        dist = np.sqrt(px * px + py * py)
        hw = ha + t * (hb - ha)
        c = np.clip((hw - dist) / aa + 0.5, 0.0, 1.0)
        m = c > cov[sy0 - by0:sy1 - by0, sx0 - bx0:sx1 - bx0]
        if not np.any(m):
            continue
        seg_len = math.sqrt(dd)
        s_here = np.float32(s_at[i]) + t * np.float32(seg_len)
        if seg_len > 1e-9:
            cross = (qx * dy - qy * dx) / np.float32(seg_len)
        else:
            cross = np.zeros_like(t)
        u_here = np.clip(cross / np.maximum(hw, 0.35), -1.6, 1.6)
        sl = (slice(sy0 - by0, sy1 - by0), slice(sx0 - bx0, sx1 - bx0))
        cov[sl] = np.where(m, c, cov[sl])
        sf[sl] = np.where(m, s_here, sf[sl])
        uf[sl] = np.where(m, u_here, uf[sl])
        vf[sl] = np.where(m, np.clip(cross, -max_half - 2.0, max_half + 2.0), vf[sl])
    return cov, sf, uf, vf, bx0, by0, float(s_at[-1]), max_half


def _streak_field(rng, s: np.ndarray, v_px: np.ndarray, s_max: float,
                  max_half_px: float, bristle_px: float, s_cell_px: float) -> np.ndarray:
    """Noise that is slow along the stroke and fast across it - the bristle pattern.

    A brush that is running dry leaves bare paper in stripes PARALLEL to the stroke,
    widening where it lifted.  Sampling the noise in (s, v) rather than in the page's
    x / y is the whole trick; in x / y the same amount of noise reads as dirt.

    ``v_px`` is the offset across the stroke in PIXELS, not normalised by the local
    width, and the lattice is indexed by it at a fixed bristle pitch.  That matters:
    normalised, a brush would always have the same number of hairs and a 1 mm passage
    would get sub-pixel hairs that just dim it evenly, which is precisely how a ring
    ends up looking like a clean vector ellipse with a few dents in it.
    """
    ns = max(4, int(s_max / max(s_cell_px, 1.0)) + 2)
    nu = max(5, int(2.0 * max_half_px / max(bristle_px, 0.5)) + 3)
    across = rng.random(nu + 1).astype(np.float32)
    # The along-stroke term has to move at a few millimetres, not a few centimetres: a
    # hair that runs out of ink picks it up again a short way on, which is what turns a
    # dry stroke into kasure (streaks that start and stop) instead of into two long
    # parallel hairs with a dead lane between them.
    along = noise(rng, nu + 1, ns + 1, 2.5, aniso=1.6)
    lat = 0.58 * across[:, None] + 0.42 * along
    ui = np.clip(v_px / max(bristle_px, 0.5) + nu * 0.5, 0.0, float(nu))
    si = np.clip(s / max(s_max, 1e-6), 0.0, 1.0) * (ns - 1)
    i0 = np.floor(ui).astype(np.int32); f0 = ui - i0
    j0 = np.floor(si).astype(np.int32); f1 = si - j0
    i1 = np.minimum(i0 + 1, nu); j1 = np.minimum(j0 + 1, ns)
    val = (lat[i0, j0] * (1 - f0) * (1 - f1) + lat[i1, j0] * f0 * (1 - f1)
           + lat[i0, j1] * (1 - f0) * f1 + lat[i1, j1] * f0 * f1)
    return val.astype(np.float32)


def brush_stroke(path_mm: np.ndarray, width_mm, *, cfg: ArtConfig, rng,
                 W: int, H: int, load=1.0, dry: float = 0.0,
                 bristle_mm: float = 0.26, streak_cell_mm: float = 2.2,
                 edge_ragged: float = 0.35, gaps: Sequence[tuple[float, float]] = (),
                 step_mm: float = 0.55, aa: float = 0.85,
                 dry_soft: float = 0.55, core: float = 0.0,
                 gap_soft_mm: float | None = None) -> Window | None:
    """Sweep a brush along a path in card millimetres.

    ``width_mm``   scalar, or an array sampled evenly along the path (interpolated).
    ``load``       scalar, or an array sampled evenly along the path.  1 = fully charged.
    ``dry``        0 no streaks, 1 a brush nearly out of ink.
    ``bristle_mm`` the pitch of the hairs, in real millimetres on the card.
    ``gaps``       (s0, s1) as FRACTIONS of arclength, where the brush left the paper.
    ``dry_soft``   how much of the dryness is carried by ink DENSITY rather than by
                   cutting bare-paper lanes.  0 is the old behaviour - a hard threshold
                   on the bristle field, which turns one wide stroke into a bundle of
                   clean full-opacity ribbons with dead lanes between them, and that is
                   exactly how a brush ring ends up reading as three concentric vector
                   circles.  1 is pure density.  Kasure is BOTH: a few genuine bare
                   lanes, and a whole stroke whose ink thins and thickens continuously
                   across and along itself.  See the module docstring.
    ``core``       how much wetter the middle of the stroke is than its edges.  A loaded
                   brush lays its darkest ink down the spine and drags out thin at the
                   flanks; 0 is a flat ink field, which reads as fill, not as ink.
    """
    ppmm = cfg.px
    pts = np.asarray(path_mm, np.float64)
    if len(pts) < 2:
        return None
    rp, s_at = resample(pts, step_mm)
    if len(rp) < 2:
        return None
    tt = s_at / max(s_at[-1], 1e-9)

    if np.isscalar(width_mm):
        w = np.full(len(rp), float(width_mm))
    else:
        src = np.asarray(width_mm, np.float64)
        w = np.interp(tt, np.linspace(0.0, 1.0, len(src)), src)
    if np.isscalar(load):
        ld = np.full(len(rp), float(load))
    else:
        src = np.asarray(load, np.float64)
        ld = np.interp(tt, np.linspace(0.0, 1.0, len(src)), src)

    half = np.maximum(w * 0.5 * ppmm, 0.12)
    res = _stroke_fields(to_px(rp, cfg), half, W, H, aa=aa)
    if res is None:
        return None
    cov, sf, uf, vf, x0, y0, s_max, max_half = res
    if s_max <= 1e-6:
        return None

    tpix = np.clip(sf / s_max, 0.0, 1.0)
    load_px = np.interp(tpix.ravel(), tt, ld).reshape(tpix.shape).astype(np.float32)

    if dry > 1e-4:
        streak = _streak_field(rng, sf, vf, s_max, max_half,
                               bristle_mm * ppmm, streak_cell_mm * ppmm)
        # A starved brush drops ink first where it carries least: low load, stroke edges.
        # The level RISES with dry, so more of the bristle pattern falls below it and
        # more bare paper shows.
        level = 0.20 + dry * (0.52 + 0.28 * (1.0 - load_px)) + 0.15 * dry * np.abs(uf)
        # HARD: the old binary cut - bare paper the moment the bristle field drops
        # below the level.  On a 4.7 mm stroke with 0.26 mm hairs that removes about
        # half the width in clean lanes, which is what turned this ring into three
        # concentric vector circles.
        hard = _smoothstep((streak - level) / 0.085)
        # A brush loses its OUTER hairs first: the spine holds ink long after the
        # flanks have dried out.  Protecting the core is what keeps a dry lap ONE
        # stroke - without it a bare lane through the middle splits the ring into two
        # arcs at that angle, which is how a single lap measures as three circles.
        if core > 1e-4:
            hard = np.maximum(hard, _smoothstep((0.30 - np.abs(uf)) / 0.18))
        # DENSITY: how much ink the hair actually carried, as a continuous field.
        dens = _smoothstep((streak - (level - 0.26)) / 0.52)
        # Coverage keeps most of the stroke: only the deepest lanes go to bare paper,
        # and the rest thins toward them instead of stopping at a hard edge.
        soft = float(np.clip(dry_soft, 0.0, 1.0))
        keep = hard + (1.0 - hard) * soft * dens
        cov = cov * (0.02 + 0.98 * keep)
        # ...and the dryness that is no longer removing ink shows up as ink that is
        # paler and warmer, which is what kasure actually looks like.
        load_px = load_px * ((1.0 - soft) * (0.30 + 0.70 * hard)
                             + soft * (0.26 + 0.74 * dens))

    if core > 1e-4:
        # the spine of the stroke carries the wettest ink; the flanks are dragged thin
        spine = np.clip(1.0 - np.abs(uf), 0.0, 1.0) ** 0.75
        load_px = load_px * (1.0 - core) + load_px * core * (0.42 + 1.05 * spine)
        load_px = np.clip(load_px, 0.0, 1.0)

    if edge_ragged > 1e-4:
        gy, gx = cov.shape
        rag = noise(rng, gy, gx, max(1.6, 0.30 * ppmm))
        band = 4.0 * cov * (1.0 - cov)           # only where the edge actually is
        cov = np.clip(cov + band * (rag - 0.5) * edge_ragged, 0.0, 1.0)

    # A LIFT IS A LENGTH, NOT A FRACTION.  The shoulder either side of a gap was
    # 0.012 of the stroke's own arclength, which on a 62 mm rule is 0.74 mm of ink
    # fading out and back in - so a 0.6 mm drawn break measured as 2.1 mm of bare
    # rule and every short side ran 5 - 10 occupancy points under its target
    # (REFERENCE_SPEC row 22; an independent pass read our top rule at 0.771 against
    # a 0.82 floor).  Given in millimetres the shoulder is the same on a 62 mm rule
    # and a 142 mm one, and the drawn break and the measured break are the same
    # number.  ``None`` keeps the old proportional behaviour for callers - the ring -
    # whose gaps are specified as angles and whose taper IS the point.
    for g0, g1 in gaps:
        lo, hi = min(g0, g1), max(g0, g1)
        if gap_soft_mm is None:
            soft = 0.012
        else:
            soft = max(1e-4, float(gap_soft_mm) * ppmm / max(s_max, 1e-6))
        m = (_smoothstep((tpix - (lo - soft)) / soft)
             * (1.0 - _smoothstep((tpix - hi) / soft)))
        cov = cov * (1.0 - m)

    return Window(x0, y0, cov.astype(np.float32), np.clip(load_px, 0.0, 1.0))


