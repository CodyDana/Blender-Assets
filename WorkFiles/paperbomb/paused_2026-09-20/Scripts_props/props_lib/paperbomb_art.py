def _rng(seed: int, tag: str) -> np.random.Generator:
    """A generator keyed by (seed, tag), so every element is reproducible on its own."""
    return np.random.default_rng([int(seed), int(zlib.crc32(tag.encode("utf8")))])


def _smoothstep(x):
    x = np.clip(x, 0.0, 1.0)
    return x * x * (3.0 - 2.0 * x)


def _smootherstep(x):
    x = np.clip(x, 0.0, 1.0)
    return x * x * x * (x * (x * 6.0 - 15.0) + 10.0)


def _cr_weights(t):
    """Catmull-Rom basis for taps at -1, 0, +1, +2."""
    t2 = t * t
    t3 = t2 * t
    return (
        -0.5 * t3 + t2 - 0.5 * t,
        1.5 * t3 - 2.5 * t2 + 1.0,
        -1.5 * t3 + 2.0 * t2 + 0.5 * t,
        0.5 * t3 - 0.5 * t2,
    )


def _sample_cr(lat: np.ndarray, ys: np.ndarray, xs: np.ndarray) -> np.ndarray:
    """Catmull-Rom sample of a lattice at independent row / column coordinates."""
    gh, gw = lat.shape
    iy = np.floor(ys).astype(np.int32)
    ix = np.floor(xs).astype(np.int32)
    fy = (ys - iy).astype(np.float32)
    fx = (xs - ix).astype(np.float32)
    wy = _cr_weights(fy)
    wx = _cr_weights(fx)
    # along x first: (gh, len(xs))
    acc_x = np.zeros((gh, xs.size), np.float32)
    for k in range(4):
        cols = np.clip(ix - 1 + k, 0, gw - 1)
        acc_x += lat[:, cols] * wx[k][None, :]
    out = np.zeros((ys.size, xs.size), np.float32)
    for k in range(4):
        rows = np.clip(iy - 1 + k, 0, gh - 1)
        out += acc_x[rows, :] * wy[k][:, None]
    return out


def _resize_bilinear(a: np.ndarray, H: int, W: int) -> np.ndarray:
    h, w = a.shape
    if (h, w) == (H, W):
        return a
    ys = np.linspace(0.0, h - 1.0, H, dtype=np.float32)
    xs = np.linspace(0.0, w - 1.0, W, dtype=np.float32)
    iy = np.clip(np.floor(ys).astype(np.int32), 0, h - 2) if h > 1 else np.zeros(H, np.int32)
    ix = np.clip(np.floor(xs).astype(np.int32), 0, w - 2) if w > 1 else np.zeros(W, np.int32)
    fy = (ys - iy)[:, None]
    fx = (xs - ix)[None, :]
    a00 = a[np.ix_(iy, ix)]
    a01 = a[np.ix_(iy, np.minimum(ix + 1, w - 1))]
    a10 = a[np.ix_(np.minimum(iy + 1, h - 1), ix)]
    a11 = a[np.ix_(np.minimum(iy + 1, h - 1), np.minimum(ix + 1, w - 1))]
    top = a00 * (1 - fx) + a01 * fx
    bot = a10 * (1 - fx) + a11 * fx
    return (top * (1 - fy) + bot * fy).astype(np.float32)


def noise(rng, H: int, W: int, cell_px: float, aniso: float = 1.0) -> np.ndarray:
    """Smooth value noise in [0, 1].  ``aniso`` > 1 stretches the cells horizontally.

    Evaluated on a grid coarse enough for the cell size and resampled up, so a 40 mm
    blotch field costs the same as a 1 mm one.
    """
    cx = max(1.5, cell_px * aniso)
    cy = max(1.5, cell_px)
    step = max(1.0, min(cy, cx) / 3.0)
    h = max(2, int(math.ceil(H / step)) + 1)
    w = max(2, int(math.ceil(W / step)) + 1)
    gh = int(h * step / cy) + 4
    gw = int(w * step / cx) + 4
    lat = rng.random((gh, gw), dtype=np.float32)
    ys = (np.arange(h, dtype=np.float32) * step) / cy + 1.5
    xs = (np.arange(w, dtype=np.float32) * step) / cx + 1.5
    return _resize_bilinear(_sample_cr(lat, ys, xs), H, W)


def fbm(rng, H: int, W: int, cell_px: float, octaves: int = 4,
        gain: float = 0.5, lacunarity: float = 2.0, aniso: float = 1.0) -> np.ndarray:
    """Fractal value noise, normalised to [0, 1]."""
    out = np.zeros((H, W), np.float32)
    amp = 1.0
    tot = 0.0
    c = cell_px
    for _ in range(octaves):
        out += amp * noise(rng, H, W, c, aniso)
        tot += amp
        amp *= gain
        c /= lacunarity
        if c < 1.6:
            break
    return out / max(tot, 1e-6)


def _box1d(a: np.ndarray, r: int, axis: int) -> np.ndarray:
    if r < 1:
        return a
    n = a.shape[axis]
    pad = [(0, 0)] * a.ndim
    pad[axis] = (r + 1, r)
    p = np.pad(a, pad, mode="edge")
    c = np.cumsum(p, axis=axis, dtype=np.float32)
    lo = np.take(c, np.arange(0, n), axis=axis)
    hi = np.take(c, np.arange(2 * r + 1, 2 * r + 1 + n), axis=axis)
    return (hi - lo) / float(2 * r + 1)


def blur(a: np.ndarray, sigma_px: float) -> np.ndarray:
    """Three box passes ~ a gaussian.  Cheap, separable, good enough for ink bleed."""
    if sigma_px <= 0.35:
        return a.astype(np.float32)
    r = max(1, int(round(sigma_px * 1.13)))
    out = a.astype(np.float32)
    for _ in range(3):
        out = _box1d(out, r, 0)
        out = _box1d(out, r, 1)
    return out


def blur_aniso(a: np.ndarray, sig_y: float, sig_x: float) -> np.ndarray:
    ry = max(0, int(round(sig_y * 1.13)))
    rx = max(0, int(round(sig_x * 1.13)))
    out = a.astype(np.float32)
    for _ in range(3):
        if ry:
            out = _box1d(out, ry, 0)
        if rx:
            out = _box1d(out, rx, 1)
    return out


