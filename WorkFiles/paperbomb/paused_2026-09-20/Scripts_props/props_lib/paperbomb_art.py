class GuideAccess(RuntimeError):
    """Something tried to open a guide image while drawing.  It must never happen."""


class no_guide_access:
    """Context manager that makes the guide-free claim testable rather than asserted.

    While it is active, any attempt to open a path containing one of
    ``FORBIDDEN_INPUT_FRAGMENTS`` raises ``GuideAccess``.  The build script wraps the
    art in it and puts the result in the report, so "no pixel of the reference images
    is in this product" is a thing the build PROVES on every run instead of a sentence
    somebody wrote once.  Grepping this file for the fragments does not prove it - the
    fragment list itself matches - but running inside this guard does.
    """

    def __init__(self, fragments: Sequence[str] = FORBIDDEN_INPUT_FRAGMENTS):
        self.fragments = tuple(f.lower().replace("\\", "/") for f in fragments)
        self._open = None
        self.opened: list[str] = []

    def _check(self, path) -> None:
        try:
            s = os.fspath(path)
        except TypeError:
            return
        if not isinstance(s, str):
            s = s.decode("utf8", "replace")
        low = s.lower().replace("\\", "/")
        for frag in self.fragments:
            if frag in low:
                raise GuideAccess(
                    "paperbomb_art tried to open %r, which is a layout reference.  The "
                    "artwork is drawn, not sampled, so nothing here may read it." % s)
        self.opened.append(s)

    def __enter__(self):
        import builtins
        self._open = builtins.open
        guard = self

        def _guarded(file, *a, **kw):
            guard._check(file)
            return guard._open(file, *a, **kw)

        builtins.open = _guarded
        # ...AND THE OTHER DOOR.  An independent pass pointed out that patching
        # ``builtins.open`` alone leaves ``bpy.data.images.load`` open, and demonstrated
        # it loading the guide from inside an active guard.  It is harmless today -
        # ``no_image_loads()`` below proves this module contains zero image loads of any
        # API - but a guard that only covers the route nobody would take is not a guard.
        # ``bpy.data.images`` is an immutable ``bpy_prop_collection`` and cannot be
        # patched on the instance or the type, so the guard swaps ``bpy.data`` itself
        # for a thin forwarding proxy whose ``images`` is wrapped.  Everything else on
        # ``bpy.data`` is passed straight through, and the real object goes back on exit.
        self._bpy = None
        self._data = None
        try:
            import bpy                                            # noqa: F401
            real = bpy.data

            class _Images:
                def __init__(self, inner):
                    self._inner = inner

                def load(self, filepath, *a, **kw):
                    guard._check(filepath)
                    return self._inner.load(filepath, *a, **kw)

                def __getattr__(self, name):
                    return getattr(self._inner, name)

                def __getitem__(self, k):
                    return self._inner[k]

                def __iter__(self):
                    return iter(self._inner)

                def __len__(self):
                    return len(self._inner)

            class _Data:
                # NO class attribute for ``images``: __getattr__ only runs when normal
                # lookup fails, so declaring it here would shadow the guard.
                def __getattr__(self, name):
                    if name == "images":
                        return _Images(real.images)
                    return getattr(real, name)

            self._bpy = bpy
            self._data = real
            bpy.data = _Data()
        except Exception:                                # pragma: no cover - no bpy
            self._bpy = None
        return self

    def __exit__(self, *exc):
        import builtins
        if self._open is not None:
            builtins.open = self._open
        if getattr(self, "_bpy", None) is not None:
            self._bpy.data = self._data
        return False


#: every way a Python module could read pixels off a file.  ``no_image_loads`` fails on
#: any of them appearing in this module's own source, which is the STATIC half of the
#: guide-free proof: ``no_guide_access`` blocks the routes at run time, this proves the
#: routes are not there to block.  An independent pass found the runtime guard covered
#: only ``builtins.open``; both halves exist now.
FORBIDDEN_IMAGE_CALLS = ("images.load", "image.open", "imread", "imload", "np.load",
                         "numpy.load", "cv2.imread", "plt.imread", "imageio.",
                         "PIL.Image", "Image.open", "load_image", "image.load")


def no_image_loads(path: str | None = None) -> dict:
    """Static proof that this module cannot read pixels off any file at all.

    Parses its own source and reports every call whose dotted name matches
    ``FORBIDDEN_IMAGE_CALLS``, plus every string literal containing a forbidden input
    fragment.  Both lists must be empty.  This is a build gate; see
    ``build_paper_bomb.collect_gates``.
    """
    import ast
    src_path = path or __file__
    with open(src_path, "r", encoding="utf-8") as fh:
        src = fh.read()
    tree = ast.parse(src, filename=src_path)

    def dotted(node):
        bits = []
        while isinstance(node, ast.Attribute):
            bits.append(node.attr)
            node = node.value
        if isinstance(node, ast.Name):
            bits.append(node.id)
        return ".".join(reversed(bits))

    calls: list[str] = []
    for n in ast.walk(tree):
        if isinstance(n, ast.Call):
            name = dotted(n.func)
            low = name.lower()
            for frag in FORBIDDEN_IMAGE_CALLS:
                if frag.lower() in low:
                    calls.append("%s:%d %s" % (os.path.basename(src_path),
                                               getattr(n, "lineno", 0), name))
                    break
    literals: list[str] = []
    for n in ast.walk(tree):
        if isinstance(n, ast.Constant) and isinstance(n.value, str):
            low = n.value.lower().replace("\\", "/")
            # the fragment list itself lives in this file; a literal only counts when it
            # looks like a PATH to a guide rather than the guard's own vocabulary
            if "references/paperbomb/" in low and low.endswith(".png"):
                literals.append("%s:%d %r" % (os.path.basename(src_path),
                                              getattr(n, "lineno", 0), n.value))
    return {
        "source": os.path.basename(src_path),
        "image_load_calls": calls,
        "guide_path_literals": literals,
        "passed": not calls and not literals,
        "checked_for": list(FORBIDDEN_IMAGE_CALLS),
    }


